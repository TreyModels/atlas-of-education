"""Global sensitivity of the Cambodia child-labour world (Sobol indices through mc.py).

Which *assumed* constants move which Cambodia outcome? The six school-value constants (vPrim/vLow/vUp in each
region) are calibrated to UIS out-of-school targets, so they are deliberately not sampled here; the priors below
are the assumed context constants of web/camchild.js -- the ones the interface marks as "assumed" and that no
history has pinned down. First-order S1 is the share of an outcome's variance a parameter explains alone;
total-order ST adds its interactions. ST below 0.05 is 'sloppy'; the few above are the stiff directions.

The simulation seed is fixed inside every evaluation, so seed noise is not counted as parameter variance.

Run from engine/:  python camchild_sobol.py [--n 64] [--workers 4]  -> results/camchild_sobol.{json,md}
"""
import argparse
import json
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import camchild as C
import mc as MC

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'results')
N_SIM, YEARS, SIM_SEED = 1500, 10, 0

PRIORS = {
    'pp_formalJobs': (0.25, 0.55, 'lin'),     # share of city jobs in the inspected/formal sector
    'pp_tutoring': (0.02, 0.10, 'lin'),       # city tutoring price
    'pp_quality': (0.50, 0.75, 'lin'),        # city school quality
    'pp_safety': (0.55, 0.75, 'lin'),         # city school safety
    'pp_localPull': (1.00, 1.50, 'lin'),      # city youth labour demand
    'rural_enterprise': (0.35, 0.75, 'lin'),  # share of rural households with a family enterprise
    'rural_distance': (0.28, 0.62, 'lin'),    # distance cost of rural secondary schooling
    'rural_quality': (0.40, 0.60, 'lin'),     # rural school quality
    'rural_safety': (0.52, 0.72, 'lin'),      # rural school safety
    'rural_localPull': (0.60, 0.95, 'lin'),   # rural local labour demand
    'rural_leftBehind': (0.12, 0.28, 'lin'),  # share of children with a migrant parent
    'rural_shockP': (0.10, 0.24, 'lin'),      # annual income-shock probability, rural
}
LAB = {
    'pp_formalJobs': 'city formal-job share', 'pp_tutoring': 'city tutoring price', 'pp_quality': 'city school quality',
    'pp_safety': 'city school safety', 'pp_localPull': 'city youth labour demand',
    'rural_enterprise': 'rural family enterprise share', 'rural_distance': 'rural distance cost',
    'rural_quality': 'rural school quality', 'rural_safety': 'rural school safety',
    'rural_localPull': 'rural local labour demand', 'rural_leftBehind': 'rural migrant-parent share',
    'rural_shockP': 'rural income-shock probability',
}
OUTCOMES = ('child_labour', 'attendance', 'rural_oos_lower')


def _over(theta):
    over = {'pp': {}, 'rural': {}}
    for k, v in theta.items():
        region, name = k.split('_', 1)
        over[region][name] = float(v)
    return over


def _simulate(theta):
    return C.simulate(N=N_SIM, years=YEARS, seed=SIM_SEED, over=_over(theta))


def _mean_last(R, region, key, index=None):
    if index is None:
        return 100.0 * float(np.mean([row[region][key] for row in R['rows'][-4:]]))
    return 100.0 * float(np.mean([row[region][key][index] for row in R['rows'][-4:]]))


# module-level outcome functions so they pickle for the worker processes
def f_child_labour(theta):
    return _mean_last(_simulate(theta), 'all', 'cl')


def f_attendance(theta):
    return _mean_last(_simulate(theta), 'all', 'attend')


def f_rural_oos_lower(theta):
    return _mean_last(_simulate(theta), 'rural', 'oos', index=1)


FUNCS = dict(child_labour=f_child_labour, attendance=f_attendance, rural_oos_lower=f_rural_oos_lower)


def main(n, workers):
    res = dict(n=n, priors='assumed constants (calibrated school-value constants excluded)',
               provenance=MC.provenance(design='sobol', master=0), outcomes={})
    for k in OUTCOMES:
        idx, meta = MC.sobol_indices(FUNCS[k], PRIORS, n=n, master=0, boot=100, workers=workers)
        res['outcomes'][k] = dict(indices=idx, meta=meta, stiff=MC.stiff_directions(idx, 0.05))
    os.makedirs(OUT, exist_ok=True)
    json.dump(res, open(os.path.join(OUT, 'camchild_sobol.json'), 'w'), indent=1)
    L = ['# Which assumptions move which Cambodia outcome: Sobol indices for camchild', '',
         f"Generated by `python camchild_sobol.py` ({n} base points, {n * (len(PRIORS) + 2):,} worlds per outcome, "
         'scrambled Sobol design, fixed simulation seed). Total-order index ST in brackets: [5-95% bootstrap]. '
         '**Bold** = stiff (ST at least 0.05). Calibrated school-value constants are not sampled: they are fitted to '
         'UIS out-of-school targets, so their sensitivity would be a statement about the calibration, not the world.', '',
         '| Parameter | ' + ' | '.join(OUTCOMES) + ' |', '|---|' + '---:|' * len(OUTCOMES)]
    for p in PRIORS:
        cells = []
        for k in OUTCOMES:
            v = res['outcomes'][k]['indices'][p]
            c = f"S1 {v['S1']:.2f}, ST {v['ST']:.2f} [{v['ST_lo']:.2f}-{v['ST_hi']:.2f}]"
            cells.append(f'**{c}**' if v['ST'] >= .05 else c)
        L.append(f'| {LAB[p]} | ' + ' | '.join(cells) + ' |')
    L += ['', '## Stiff directions per outcome', '']
    for k in OUTCOMES:
        stiff = res['outcomes'][k]['stiff']
        L.append(f"- **{k}**: " + (', '.join(f"{LAB[p]} ({res['outcomes'][k]['indices'][p]['ST']:.2f})" for p in stiff)
                                   if stiff else 'none above the 0.05 threshold'))
    L += ['', 'Reading: S1 summing well below 1 means interactions carry the outcome; ST much larger than S1 marks a '
          'parameter that matters only in combination. A parameter outside every stiff list cannot be pinned down by '
          'matching these outcomes, so it stays a declared assumption. **Caveat:** at n=64 some first-order S1 '
          'estimates fall outside [0, 1] (negative, or above 1); that is estimator noise, not a share. Read the '
          'total-order ST and its bootstrap interval for the stiff/sloppy ordering; do not read the S1 point values '
          'as variance shares at this n. A larger n (256+) is needed for precise shares.']
    open(os.path.join(OUT, 'camchild_sobol.md'), 'w').write('\n'.join(L) + '\n')
    print('\n'.join(L))


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('--n', type=int, default=64, help='base points, power of two (default 64)')
    ap.add_argument('--workers', type=int, default=4, help='worker processes (default 4)')
    a = ap.parse_args()
    main(a.n, a.workers)
