"""Export everything the browser app needs: model inputs, fitted parameters, Python reference runs (for the JS parity
test), and the calibration / Tilly result tables.

Run from engine/:  python -m firms.export_web   -> ../web/data/atlas_data.js  (a JS file setting window.ATLAS_DATA)
"""
import json, math, os, sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from firms import model as M, categorical as C, data_china as D

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, 'results')
WEB = os.path.join(os.path.dirname(os.path.dirname(HERE)), 'web', 'data')


def clean(x):
    if isinstance(x, float):
        return None if (math.isnan(x) or math.isinf(x)) else round(x, 10)
    if isinstance(x, dict):
        return {k: clean(v) for k, v in x.items() if not callable(v)}
    if isinstance(x, (list, tuple)):
        return [clean(v) for v in x]
    return x


def main():
    base = M.YouthMarket(D)
    p = base.p
    months = list(M._months(p['start'], p['end']))
    inputs = dict(
        months=[[y, m] for y, m in months],
        A=[base.A.get((y, m), 1.0) for y, m in months],          # at default m_a; the browser recomputes A from `adult`
        adult=[base.adult.get((y, m)) for y, m in months],       # seasonally adjusted adult unemployment rate (share)
        adult_ref=float(sum(v for k, v in base.adult.items() if p['ref_years'][0] <= k[0] <= p['ref_years'][1]) /
                        sum(1 for k in base.adult if p['ref_years'][0] <= k[0] <= p['ref_years'][1])),
        property=[D.property_index(y, m) for y, m in months],
        years=list(range(p['start'][0], p['end'][0] + 2)),
        graduates=[D.graduates(y) for y in range(p['start'][0], p['end'][0] + 2)],
        nongrad=[D.nongrad_school_leavers(y) for y in range(p['start'][0], p['end'][0] + 2)],
        youth=[[y, m, *D.youth(y, m)] for y in range(2018, 2027) for m in range(1, 13) if D.youth(y, m)],
        urban=[[y, m, *D.urban(y, m)] for y in range(2018, 2027) for m in range(1, 13) if D.urban(y, m)],
        sources=D.SOURCES,
    )
    ref = dict(S_ref=list(p['S_ref']), g_H=p['g_H'], g_N=p['g_N'])
    fit = json.load(open(os.path.join(RES, 'china_fit.json')))
    tfit = json.load(open(os.path.join(RES, 'tilly_fit.json')))
    tilly_tab = json.load(open(os.path.join(RES, 'tilly.json')))
    head = fit['profiles']['full|sigma_A=5.0']['params']
    tilly_params = dict(tfit['params'], **{k: v for k, v in tfit['fixed'].items()})
    defaults = {k: v for k, v in M.DEFAULTS.items() if not callable(v) and v is not None}
    defaults.update(ref)
    # Python reference runs for the JS parity test
    keys = ('rate_old', 'rate_new', 'slack', 'u_G', 'u_N', 'waiting', 'c_req', 'u_G_in', 'u_G_out', 'f_g', 'V_n')
    refruns = {}
    for name, kw in (('headline', head), ('tilly', tilly_params), ('tilly_random', dict(tilly_params, rank='random'))):
        R = C.CategoricalMarket(D, **dict(ref, **kw)).run()
        refruns[name] = {k: R[k] for k in keys}
    out = dict(
        version='0.7', inputs=inputs, defaults=defaults, tilly_defaults=C.TILLY_DEFAULTS,
        params=dict(headline=head, tilly=tilly_params), refruns=refruns,
        profiles={k: {kk: v[kk] for kk in ('fit_early', 'holdout_old_2023H1', 'new_verified', 'rate_change', 'supply_effect', 'vg_2025H1_pct')}
                  for k, v in fit['profiles'].items()},
        shapley=fit['shapley_rate_new'], shapley_grad=fit['shapley_grad_u'], diagnostics=fit['diagnostics'],
        naive=dict(old_2023H1=fit['naive_old_2023H1'], new_verified=fit['naive_new_verified']),
        tilly_experiments=tilly_tab, tilly_fit={k: v for k, v in tfit.items() if k != 'series'},
    )
    os.makedirs(WEB, exist_ok=True)
    with open(os.path.join(WEB, 'atlas_data.js'), 'w') as f:
        f.write('/* Generated by engine/firms/export_web.py. Do not edit by hand. */\n')
        f.write('(typeof window !== "undefined" ? window : globalThis).ATLAS_DATA = ' + json.dumps(clean(out), separators=(',', ':')) + ';\n')
        f.write("if (typeof module !== 'undefined') module.exports = globalThis.ATLAS_DATA;\n")
    print('wrote', os.path.join(WEB, 'atlas_data.js'))


if __name__ == '__main__':
    main()
