"""Pin the graduate wage-adjustment speed lam_g from starting-wage data, then rerun the strict forecast.

The strict forecast (forecast_strict.py) showed that lam_g decides the 2023-26 forecast and that 2018-22 youth
unemployment cannot identify it. Here lam_g is chosen from data that were PUBLIC at the cutoff (Dec 2022): MyCOS
starting wages for the classes of 2018-2021 relative to the NBS urban average wage. For every lam_g on a grid the other
parameters are refitted to 2018-22 youth unemployment exactly as in the strict forecast; the grid point whose modelled
graduate wage path (Dec of each class year, log change from 2018) best matches the observed relative starting wage is
selected. Only then is the 2023-26 forecast scored. Classes 2022-23 are held out as a wage check.

Run from engine/:  python -m firms.wage_anchor  -> firms/results/wage_anchor.{json,md}
"""
import json, math, os, sys
import numpy as np

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from firms import data_china as D, forecast_strict as F, calibrate_china as C

OUT = F.OUT
GRID = [0.002, 0.005, 0.01, 0.02, 0.05, 0.1, 0.2, 0.5]
KNOWN = [y for y in D.STARTING_WAGE_BA if 2018 <= y and D.STARTING_WAGE_PUBLISHED[y] <= F.CUTOFF and y in D.URBAN_WAGE]
TEST = [y for y in (2022, 2023) if y in D.URBAN_WAGE]


def model_wage_path(R, years):
    w = {y: v for y, m, v in zip(R['year'], R['month'], R['w_g']) if m == 12}
    return {y: math.log(w[y] / w[2018]) for y in years}


def observed_path(years):
    return {y: math.log(D.relative_starting_wage(y) / D.relative_starting_wage(2018)) for y in years}


def main(nstarts=3):
    over0 = dict(sigma_A=5.0)
    obs_k, obs_t = observed_path(KNOWN), observed_path(TEST)
    rows = []
    for lam in GRID:
        o = dict(over0, lam_g=lam)
        b = F.fit(o, nstarts)
        R = F.run(b.x, 'strict', o)
        mk = model_wage_path(R, KNOWN); mt = model_wage_path(R, TEST)
        wage_rmse = float(np.sqrt(np.mean([(mk[y] - obs_k[y]) ** 2 for y in KNOWN if y != 2018])))
        rows.append(dict(lam_g=lam, wage_rmse_known=wage_rmse,
                         wage_err_test={y: mt[y] - obs_t[y] for y in TEST},
                         model_path={**mk, **mt}, fit_mae=C.stats(F.obs_pairs(R, *F.FIT, 'old'))['mae'],
                         **F.score(R), params={n: float(v) for (n, *_), v in zip(C.FREE, b.x)}))
        print(f"lam_g={lam}: wage rmse {wage_rmse:.3f}  fit {rows[-1]['fit_mae']:.2f}  "
              f"new-method MAE {rows[-1]['new_verified']['mae']:.2f}", flush=True)
    pick = min(rows, key=lambda r: r['wage_rmse_known'])
    res = dict(known_classes=KNOWN, test_classes=TEST, observed={**obs_k, **obs_t}, rows=rows, picked=pick['lam_g'],
               naive=F.score(f=F.naive('same_month_2022')))
    json.dump(res, open(os.path.join(OUT, 'wage_anchor.json'), 'w'), indent=1, default=str)
    report(res, pick)
    return res


def report(res, pick):
    nv = res['naive']
    L = ['# Graduate wage speed pinned from starting wages', '',
         'Generated by `python -m firms.wage_anchor`. lam_g is chosen ONLY from MyCOS starting wages for the classes of '
         f"{', '.join(map(str, res['known_classes']))} (public by mid-2022), relative to the NBS urban average wage. "
         'The other parameters are refitted to 2018-22 youth unemployment with data as of Dec 2022 (strict '
         'information set) at every grid point.', '',
         'Observed log change in the relative starting wage since 2018: ' +
         ', '.join(f"{y} {v:+.3f}" for y, v in res['observed'].items() if y != 2018) +
         f" (classes {', '.join(map(str, res['test_classes']))} held out).", '',
         '| lam_g | Wage RMSE, known classes | Wage error 2022 / 2023 (held out) | 2018-22 fit MAE | 2023 H1 MAE | New-method MAE | New-method bias |',
         '|---:|---:|---|---:|---:|---:|---:|']
    for r in res['rows']:
        t = ' / '.join(f"{v:+.3f}" for v in r['wage_err_test'].values())
        star = ' **(picked)**' if r is pick else ''
        L.append(f"| {r['lam_g']}{star} | {r['wage_rmse_known']:.3f} | {t} | {r['fit_mae']:.2f} | "
                 f"{r['old_2023H1']['mae']:.2f} | {r['new_verified']['mae']:.2f} | {r['new_verified']['bias']:+.2f} |")
    L += ['', f"Naive (same month of 2022): 2023 H1 MAE {nv['old_2023H1']['mae']:.2f}, new-method MAE "
          f"{nv['new_verified']['mae']:.2f}.", '',
          f"**Verdict.** With lam_g = {pick['lam_g']} chosen from pre-cutoff wages, the strict forecast scores "
          f"{pick['new_verified']['mae']:.2f} on new-method months against {nv['new_verified']['mae']:.2f} for naive "
          f"({'beats' if pick['new_verified']['mae'] < nv['new_verified']['mae'] else 'loses to'} naive) and "
          f"{pick['old_2023H1']['mae']:.2f} on 2023 H1 against {nv['old_2023H1']['mae']:.2f} "
          f"({'beats' if pick['old_2023H1']['mae'] < nv['old_2023H1']['mae'] else 'loses to'} naive).", '',
          'Caveats: the model wage is the wage on all graduate jobs, while MyCOS measures new graduates six months '
          'out; the urban non-private average wage over-represents state and large employers; four classes give '
          'three changes, so the anchor is coarse.']
    open(os.path.join(OUT, 'wage_anchor.md'), 'w').write('\n'.join(L) + '\n')
    print('\n'.join(L))


if __name__ == '__main__' and '--joint' not in sys.argv:
    main()


# ------------------------------------------------------------------ joint fit: wages and youth unemployment, pre-cutoff
JOINT_EXTRA = [('g_H_shift', -0.10, 0.05, 0.0)]       # change to the graduate demand drift g_H (per year)
W_WAGE = math.sqrt(60 / 3)                          # balance 3 wage changes against 60 youth months; 1% = 1 pt


def joint_resid(x, over):
    th, dg = x[:-1], x[-1]
    o = dict(over, g_H=C.REF['g_H'] + dg)
    R = F.run(th, 'strict', o)
    pr = F.obs_pairs(R, *F.FIT, 'old')
    r = [mod - ob for *_, ob, mod, _ in pr]
    if not all(map(math.isfinite, r)):
        return np.full(len(pr) + 3, 50.0)
    mk, ob = model_wage_path(R, KNOWN), observed_path(KNOWN)
    r += [W_WAGE * 100 * (mk[y] - ob[y]) for y in KNOWN if y != 2018]
    return np.array(r)


def joint_fit(nstarts=6, seed=2):
    from scipy.optimize import least_squares
    spec = C.FREE + JOINT_EXTRA
    lo = [f[1] for f in spec]; hi = [f[2] for f in spec]
    rng = np.random.default_rng(seed)
    starts = [np.array([f[3] for f in spec])] + [rng.uniform(lo, hi) for _ in range(nstarts - 1)]
    over = dict(sigma_A=5.0)
    best = None
    for s in starts:
        try:
            r = least_squares(joint_resid, s, bounds=(lo, hi), diff_step=1e-3, max_nfev=300, args=(over,))
        except ValueError:
            continue
        if best is None or r.cost < best.cost:
            best = r
    th, dg = best.x[:-1], best.x[-1]
    o = dict(over, g_H=C.REF['g_H'] + dg)
    R = F.run(th, 'strict', o)
    path = model_wage_path(R, KNOWN + TEST)
    res = dict(params={**{n: float(v) for (n, *_), v in zip(C.FREE, th)}, 'g_H': C.REF['g_H'] + float(dg),
                       'g_H_base': C.REF['g_H']},
               at_bounds=[n for (n, lo_, hi_, _), v in zip(spec, best.x) if min(v - lo_, hi_ - v) < 1e-2 * (hi_ - lo_)],
               model_wage=path, observed=observed_path(KNOWN + TEST),
               fit_mae=C.stats(F.obs_pairs(R, *F.FIT, 'old'))['mae'], **F.score(R),
               naive=F.score(f=F.naive('same_month_2022')))
    json.dump(res, open(os.path.join(OUT, 'wage_joint.json'), 'w'), indent=1)
    nv = res['naive']
    L = ['', '## Joint fit: wages and unemployment, data as of Dec 2022', '',
         'All eleven parameters plus a shift in the graduate demand drift g_H fitted together to 2018-22 youth '
         'unemployment and the 2019-21 relative starting-wage changes (equal total weight).', '',
         '| Class | Observed | Model |', '|---|---:|---:|']
    L += [f"| {y}{' (held out)' if y in TEST else ''} | {res['observed'][y]:+.3f} | {path[y]:+.3f} |"
          for y in KNOWN + TEST if y != 2018]
    L += ['', f"g_H: {res['params']['g_H_base']:.4f} -> {res['params']['g_H']:.4f} per year; lam_g "
          f"{res['params']['lam_g']:.3f}. Parameters at a bound: {', '.join(res['at_bounds']) or 'none'}.", '',
          f"2018-22 fit MAE {res['fit_mae']:.2f}. Forecast: 2023 H1 MAE {res['old_2023H1']['mae']:.2f} "
          f"(naive {nv['old_2023H1']['mae']:.2f}); new-method MAE {res['new_verified']['mae']:.2f}, bias "
          f"{res['new_verified']['bias']:+.2f} (naive {nv['new_verified']['mae']:.2f})."]
    L += ['', '## What this establishes', '',
          '1. Starting wages cannot pin lam_g in this model: with g_H fixed from 2010-18, no wage speed reproduces the '
          'steady erosion of the graduate premium, because the model has none before 2021.',
          '2. Freeing the graduate demand drift lets the model match 2019-21 wages, but only with demand for graduates '
          'shrinking by about 7% a year (the shift is at its bound), and it then overshoots the held-out 2022-23 wages.',
          '3. With wages matched, the forecast is as bad as before (5.6 vs naive 1.7). In this model falling wages '
          'clear the graduate queue. In China, graduate wages fell AND youth unemployment stayed high. The two-type '
          'model cannot produce that combination; a state that keeps graduates out of the job queue while wages fall '
          '(waiting for exams or secure posts: the Tilly waiting pool) is the next candidate.']
    open(os.path.join(OUT, 'wage_anchor.md'), 'a').write('\n'.join(L) + '\n')
    print('\n'.join(L))
    return res


if __name__ == '__main__' and '--joint' in sys.argv:
    joint_fit()
