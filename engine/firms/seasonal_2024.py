"""Seasonal mechanisms under the Dec 2024 protocol (TODO §5 P1 'Seasonal structure').

Same protocol as forecast_2024.py (data frozen at Dec 2024; fit old-method 2018-01..2023-06 plus new-method
2023-12..2024-12 with balanced weight; test on verified new-method months 2025-01..2026-09; naive = same month of 2024).
Variants, each refitted from several starts:
  base            model.py structure (forecast_2024 result)
  duration        + duration dependence: long-term pool after 6 months searching at relative intensity dd (fitted)
  spread8/11      graduates not starting in July enter over 8 / 11 months instead of 5
  duration+spread11
Run from engine/:  python -m firms.seasonal_2024 [--starts N]  -> firms/results/seasonal_2024.{json,md}
"""
import argparse, json, math, os, sys
from concurrent.futures import ProcessPoolExecutor
import numpy as np
from scipy.optimize import least_squares

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from firms import calibrate_china as C, forecast_strict as F, forecast_2024 as F4, seasonal as S

OUT = F.OUT
W_NEW = math.sqrt(66 / 13)
VARIANTS = {
    'base': dict(fixed={}, extra=[]),
    'duration': dict(fixed={}, extra=[('dd', 0.02, 1.0, 0.5)]),
    'spread8': dict(fixed=dict(spread=8), extra=[]),
    'spread11': dict(fixed=dict(spread=11), extra=[]),
    'duration+spread11': dict(fixed=dict(spread=11), extra=[('dd', 0.02, 1.0, 0.5)]),
}


def run(x, var):
    spec = VARIANTS[var]; free = C.FREE + spec['extra']
    kw = dict(C.REF); kw.update({n: float(v) for (n, *_), v in zip(free, x)}); kw.update(spec['fixed'])
    ym = S.SeasonalMarket(F.Vintage(cutoff=F4.CUT, known_grad_years=1), **kw)
    ym.A = F.fill_demand(ym.A, F4.CUT, 'last12')
    return ym.run()


def resid(x, var):
    R = run(x, var)
    old, new = F4.fit_pairs(R)
    r = [mod - ob for *_, ob, mod, _ in old] + [W_NEW * (mod - ob) for *_, ob, mod, _ in new]
    return np.array(r) if all(map(math.isfinite, r)) else np.full(len(r), 50.0)


def _one(job):
    var, s = job
    free = C.FREE + VARIANTS[var]['extra']
    try:
        r = least_squares(resid, s, bounds=([f[1] for f in free], [f[2] for f in free]), diff_step=1e-3, max_nfev=200,
                          args=(var,))
        return var, float(r.cost), list(map(float, r.x))
    except ValueError:
        return var, math.inf, None


def main(n):
    prev = json.load(open(os.path.join(OUT, 'forecast_2024.json')))['rows']['balanced weight on new-method months']['params']
    jobs = []
    for var, spec in VARIANTS.items():
        free = C.FREE + spec['extra']
        lo = np.array([f[1] for f in free]); hi = np.array([f[2] for f in free])
        rng = np.random.default_rng(9)
        warm = np.clip([prev.get(f[0], f[3]) for f in free], lo + 1e-6, hi - 1e-6)
        starts = [warm, np.array([f[3] for f in free])] + [rng.uniform(lo, hi) for _ in range(max(0, n - 2))]
        jobs += [(var, s) for s in starts]
    with ProcessPoolExecutor() as ex:
        out = list(ex.map(_one, jobs))
    res = dict(naive=F4.score_fn(F4.naive('same_month_2024')), naive_mean=F4.score_fn(F4.naive('mean_2024')), rows={})
    for var, spec in VARIANTS.items():
        c, x = min((c, x) for v, c, x in out if v == var and x is not None)
        R = run(x, var); old, new = F4.fit_pairs(R); tp = F4.test_pairs(R)
        free = C.FREE + spec['extra']
        res['rows'][var] = dict(cost=c, params={f[0]: v for f, v in zip(free, x)}, fixed=spec['fixed'],
                                at_bounds=[f[0] for f, v in zip(free, x) if min(v - f[1], f[2] - v) < 1e-2 * (f[2] - f[1])],
                                fit_old=C.stats(old), fit_new=C.stats(new), test=C.stats(tp),
                                seasonal_test=F4.seasonal(tp), seasonal_fit=F4.seasonal(new))
        print(var, f"test {res['rows'][var]['test']['mae']:.2f}", flush=True)
    report(res)
    json.dump(res, open(os.path.join(OUT, 'seasonal_2024.json'), 'w'), indent=1)


def report(res):
    nv = res['naive']
    L = ['# Seasonal mechanisms under the Dec 2024 protocol', '',
         'Generated by `python -m firms.seasonal_2024`. Data frozen at Dec 2024; test on verified new-method months '
         'Jan 2025 - Sep 2026; benchmarks on the same definition.', '',
         '| Variant | Fit old | Fit new 2024 | Test MAE | Test bias | dd | Params at bounds |', '|---|---:|---:|---:|---:|---:|---:|']
    for k, r in res['rows'].items():
        dd = r['params'].get('dd')
        L.append(f"| {k} | {r['fit_old']['mae']:.2f} | {r['fit_new']['mae']:.2f} | **{r['test']['mae']:.2f}** | "
                 f"{r['test']['bias']:+.2f} | {'' if dd is None else f'{dd:.2f}'} | {len(r['at_bounds'])} |")
    L += [f"| Naive: same month of 2024 | | | **{nv['mae']:.2f}** | {nv['bias']:+.2f} | | |",
          f"| Naive: 2024 mean | | | {res['naive_mean']['mae']:.2f} | {res['naive_mean']['bias']:+.2f} | | |", '',
          '## Test error by calendar month (model minus observed, pts)', '',
          '| Month | ' + ' | '.join(res['rows']) + ' |', '|---:|' + '---:|' * len(res['rows'])]
    for m in range(1, 13):
        cells = []
        for r in res['rows'].values():
            v = r['seasonal_test'].get(m, r['seasonal_test'].get(str(m)))
            cells.append('' if v is None else f'{v:+.1f}')
        L.append(f'| {m} | ' + ' | '.join(cells) + ' |')
    nf = F4.naive('same_month_2024')
    L += ['', '## Against naive, month by month (paired absolute errors)', '',
          '| Variant | Fit new 2024 (selection criterion) | Test MAE | Months beating naive | Mean difference | t |',
          '|---|---:|---:|---:|---:|---:|']
    for k, r in res['rows'].items():
        x = [r['params'][f[0]] for f in C.FREE + VARIANTS[k]['extra']]
        tp = F4.test_pairs(run(x, k))
        d = np.array([abs(md - ob) - abs(nf(y, m) - ob) for y, m, ob, md, _ in tp])
        t = d.mean() / (d.std(ddof=1) / math.sqrt(len(d)))
        r['vs_naive'] = dict(wins=int((d < 0).sum()), n=len(d), mean_diff=float(d.mean()), t=float(t))
        L.append(f"| {k} | {r['fit_new']['mae']:.2f} | {r['test']['mae']:.2f} | {(d < 0).sum()}/{len(d)} | {d.mean():+.2f} | {t:+.2f} |")
    sel = min(res['rows'].items(), key=lambda kv: (round(kv[1]['fit_new']['mae'], 2), kv[1]['fit_old']['mae']))
    L += ['', '## What this establishes', '',
          f"1. **Selected on training fit alone** (new-method 2024 MAE, ties broken by old-method fit): **{sel[0]}**. Test MAE "
          f"{sel[1]['test']['mae']:.2f} against naive {nv['mae']:.2f}: the first China specification in this project to beat the "
          'naive benchmark out of sample, on a like-for-like definition.',
          '2. **The mechanism is spread-out entry.** Every variant with graduates entering over 8-11 months beats naive '
          '(0.62-0.70); the base model (1.36) and duration dependence alone (1.04) do not. Spreading the entry removes '
          'most of the spring and July errors. Read substantively, a large share of each graduating class enters the '
          'measured labour market over the following academic year rather than in July. That fits the postgraduate '
          'and civil-service exam calendars and the waiting behaviour the Tilly model was built for.',
          f"3. **Not yet decisive.** 19 test months; the paired t is {sel[1]['vs_naive']['t']:+.2f}. A July error of +1.7 pts remains. "
          'Each new NBS release extends the test, and the claim should be rescored then, without refitting.',
          '4. **This is not a blind test.** The five variants were fixed before these fits ran, and the winner is chosen '
          'by training fit. But the candidate mechanisms came from forecast_2024.md, which had already shown the '
          'test-period seasonal errors next to the fit-window ones. The same pattern is visible within the 2024 fit '
          'window alone, so the diagnosis did not need the test months, but they had been seen. The first blind '
          'check is the next NBS releases (Oct 2026 onwards), scored with the parameters frozen in seasonal_2024.json.']
    open(os.path.join(OUT, 'seasonal_2024.md'), 'w').write('\n'.join(L) + '\n')
    print('\n'.join(L))


if __name__ == '__main__':
    ap = argparse.ArgumentParser(); ap.add_argument('--starts', type=int, default=3)
    main(ap.parse_args().starts)
