"""Strict information-set forecast for the Tilly categorical model (TODO §5 P1, after wage_anchor.py).

Question: the two-type model cannot produce falling graduate wages AND persistent youth unemployment together, because
falling wages clear its queue. The categorical model adds secure posts that are rationed and partly hoarded, and
graduates who leave the measured labour force to wait for them. Does that change the forecast when the model only sees
data available at the end of 2022?

Same protocol as forecast_strict.py: Vintage data frozen at Dec 2022, demand index and seasonal adjustment on
pre-cutoff data, prespecified rules for later inputs, scored on 2023 H1 (old method) and verified new-method months.
Two fits, each from several starts in parallel:
  U   2018-22 youth unemployment only
  UW  2018-22 youth unemployment plus 2019-21 relative starting wages (public by mid-2022), equal total weight
Held-out wage classes 2022-23 are reported for both.

Run from engine/:  python -m firms.tilly_strict [--starts N]  -> firms/results/tilly_strict.{json,md}
"""
import argparse, json, math, os, sys
from concurrent.futures import ProcessPoolExecutor
import numpy as np
from scipy.optimize import least_squares

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from firms import categorical as CM, calibrate_china as K, forecast_strict as F, tilly_fit as T, wage_anchor as W

OUT = F.OUT
FREE = T.FREE


def run(th, over=None):
    kw = dict(K.REF, **T.FIXED)
    kw.update({n: float(v) for (n, *_), v in zip(FREE, th)}); kw.update(over or {})
    ym = CM.CategoricalMarket(F.Vintage(), **kw)
    ym.A = F.fill_demand(ym.A, F.CUTOFF, 'last12')
    return ym.run()


def resid(th, mode):
    R = run(th)
    pr = F.obs_pairs(R, *F.FIT, 'old')
    r = [mod - ob for *_, ob, mod, _ in pr]
    if not all(map(math.isfinite, r)):
        return np.full(len(pr) + (3 if mode == 'UW' else 0), 50.0)
    if mode == 'UW':
        mk, ob = W.model_wage_path(R, W.KNOWN), W.observed_path(W.KNOWN)
        r += [W.W_WAGE * 100 * (mk[y] - ob[y]) for y in W.KNOWN if y != 2018]
    return np.array(r)


def _one(args):
    s, mode = args
    lo = [f[1] for f in FREE]; hi = [f[2] for f in FREE]
    try:
        r = least_squares(resid, s, bounds=(lo, hi), diff_step=1e-3, max_nfev=150, args=(mode,))
        return float(r.cost), list(map(float, r.x))
    except ValueError:
        return math.inf, None


def starts(n, seed=4):
    lo = np.array([f[1] for f in FREE]); hi = np.array([f[2] for f in FREE])
    prev = json.load(open(os.path.join(OUT, 'tilly_fit.json')))['params']
    S = [np.array([f[3] for f in FREE]), np.clip([prev[f[0]] for f in FREE], lo + 1e-6, hi - 1e-6)]
    rng = np.random.default_rng(seed)
    return S + [rng.uniform(lo, hi) for _ in range(max(0, n - 2))]


def summarise(th, mode, cost):
    R = run(th)
    path = W.model_wage_path(R, W.KNOWN + W.TEST)
    obs = W.observed_path(W.KNOWN + W.TEST)
    m = lambda k, a, b: K.window_mean(R, k, a, b)
    return dict(mode=mode, cost=cost, params={n: float(v) for (n, *_), v in zip(FREE, th)},
                at_bounds=[n for (n, lo, hi, _), v in zip(FREE, th) if min(v - lo, hi - v) < 1e-2 * (hi - lo)],
                fit_mae=K.stats(F.obs_pairs(R, *F.FIT, 'old'))['mae'], **F.score(R),
                wage_model=path, wage_obs=obs,
                waiting_2022=m('waiting', (2022, 1), (2022, 12)), waiting_2025=m('waiting', (2025, 1), (2025, 12)),
                slack_2022=m('slack', (2022, 1), (2022, 12)), slack_2025=m('slack', (2025, 1), (2025, 12)),
                rate_new_2025=m('rate_new', (2025, 1), (2025, 12)))


def main(n):
    jobs = [(s, mode) for mode in ('U', 'UW') for s in starts(n)]
    with ProcessPoolExecutor() as ex:
        out = list(ex.map(_one, jobs))
    res = {}
    for mode in ('U', 'UW'):
        cand = [(c, x) for (s, md), (c, x) in zip(jobs, out) if md == mode and x is not None]
        c, x = min(cand)
        res[mode] = summarise(x, mode, c)
        res[mode]['all_starts'] = sorted(c for c, _ in cand)
    res['naive'] = F.score(f=F.naive('same_month_2022'))
    res['two_type_strict'] = json.load(open(os.path.join(OUT, 'forecast_strict.json')))['scores'][
        'strict (vintage Dec 2022, rules for future inputs)']
    json.dump(res, open(os.path.join(OUT, 'tilly_strict.json'), 'w'), indent=1)
    report(res)


def report(res):
    nv, tt = res['naive'], res['two_type_strict']
    L = ['# Strict forecast with Tilly mechanisms', '',
         'Generated by `python -m firms.tilly_strict`. Categorical model (secure posts 10% of graduate entry, 40% '
         'hoarded, waiting outside the labour force, emulation, 20% outsider wedge) fitted to data as of Dec 2022 '
         'only. U = fitted to youth unemployment 2018-22; UW = also to 2019-21 relative starting wages.', '',
         '| Model | 2018-22 fit MAE | 2023 H1 MAE | New-method MAE | New-method bias |', '|---|---:|---:|---:|---:|',
         f"| Naive (same month of 2022) | | {nv['old_2023H1']['mae']:.2f} | {nv['new_verified']['mae']:.2f} | {nv['new_verified']['bias']:+.2f} |",
         f"| Two-type, strict | 1.35 | {tt['old_2023H1']['mae']:.2f} | {tt['new_verified']['mae']:.2f} | {tt['new_verified']['bias']:+.2f} |"]
    for k, lab in (('U', 'Tilly, strict, unemployment only'), ('UW', 'Tilly, strict, unemployment + wages')):
        r = res[k]
        L.append(f"| {lab} | {r['fit_mae']:.2f} | {r['old_2023H1']['mae']:.2f} | {r['new_verified']['mae']:.2f} | "
                 f"{r['new_verified']['bias']:+.2f} |")
    L += ['', '## Graduate starting wage (log change since 2018; 2022-23 held out)', '',
          '| Class | Observed | Tilly U | Tilly UW |', '|---|---:|---:|---:|']
    for y in W.KNOWN + W.TEST:
        if y == 2018:
            continue
        L.append(f"| {y}{' (held out)' if y in W.TEST else ''} | {res['U']['wage_obs'][str(y)] if isinstance(next(iter(res['U']['wage_obs'])), str) else res['U']['wage_obs'][y]:+.3f} | "
                 f"{res['U']['wage_model'][y]:+.3f} | {res['UW']['wage_model'][y]:+.3f} |")
    L += ['', '## Mechanism states', '', '| | Tilly U | Tilly UW |', '|---|---:|---:|']
    for k, lab in (('waiting_2022', 'Graduates waiting, 2022 (m)'), ('waiting_2025', 'Graduates waiting, 2025 (m)'),
                   ('slack_2022', 'Slack incl. waiting, 2022 (%)'), ('slack_2025', 'Slack incl. waiting, 2025 (%)'),
                   ('rate_new_2025', 'Official rate, 2025 (%)')):
        L.append(f"| {lab} | {res['U'][k]:.2f} | {res['UW'][k]:.2f} |")
    for k in ('U', 'UW'):
        r = res[k]
        L += ['', f"**{k}** parameters: " + ', '.join(f"{n} {v:.3g}" for n, v in r['params'].items()) +
              f". At a bound: {', '.join(r['at_bounds']) or 'none'}. Start costs: " +
              ', '.join(f"{c:.0f}" for c in r['all_starts']) + '.']
    open(os.path.join(OUT, 'tilly_strict.md'), 'w').write('\n'.join(L) + '\n')
    print('\n'.join(L))


if __name__ == '__main__':
    ap = argparse.ArgumentParser(); ap.add_argument('--starts', type=int, default=4)
    main(ap.parse_args().starts)
