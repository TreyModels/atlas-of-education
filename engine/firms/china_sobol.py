"""Global sensitivity of the China youth labour-market model (Sobol indices through mc.py).

Which structural parameters move which China outcome? The priors are the broad behavioural ranges the model
declares, not the fitted point: the point of the exercise is to see which directions the model's own outcomes are
stiff in, and therefore which a fit could in principle pin down.

The simulation is deterministic given a parameter vector (no random seed), so every evaluation is noise-free.

Run from engine/:  python -m firms.china_sobol [--n 256] [--workers 6]  -> firms/results/china_sobol.{json,md}
"""
import argparse
import json
import os

import numpy as np

from . import model as M, data_china as D
import mc as MC

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'results')

# reference stocks and supply drifts from the default model, held fixed so the Sobol is over parameters only
_Y = M.YouthMarket(D)
REF = dict(S_ref=_Y.p['S_ref'], g_H=_Y.p['g_H'], g_N=_Y.p['g_N'])

PRIORS = {
    'f_g_ref': (0.05, 0.35, 'lin'),    # reference graduate job-finding rate
    'f_n_ref': (0.05, 0.35, 'lin'),    # reference non-graduate job-finding rate
    's_g': (0.010, 0.035, 'lin'),      # graduate separation rate
    's_n': (0.015, 0.050, 'lin'),      # non-graduate separation rate
    'chi': (0.10, 0.60, 'lin'),        # on-the-job search intensity of downgraded graduates
    'p_g0': (1.30, 2.00, 'lin'),       # graduate productivity
    'p_n0': (0.85, 1.30, 'lin'),       # non-graduate productivity
    'z_g': (0.50, 0.90, 'lin'),        # graduate flow value of unemployment
    'z_n': (0.30, 0.72, 'lin'),        # non-graduate flow value of unemployment
    'lam_g': (0.005, 0.50, 'log'),     # graduate wage adjustment speed
    'zeta': (0.00, 0.80, 'lin'),       # share of final-year students searching (old NBS method)
}
LAB = {
    'f_g_ref': 'graduate job-finding rate', 'f_n_ref': 'non-graduate job-finding rate',
    's_g': 'graduate separation', 's_n': 'non-graduate separation',
    'chi': 'downgraded on-the-job search', 'p_g0': 'graduate productivity', 'p_n0': 'non-graduate productivity',
    'z_g': 'graduate value of unemployment', 'z_n': 'non-graduate value of unemployment',
    'lam_g': 'graduate wage speed', 'zeta': 'final-year student search share',
}
OUTCOMES = ('rate_2026', 'waiting_end', 'under_2026')


def _run(theta):
    return M.YouthMarket(D, **dict(REF, **theta)).run()


def _mask(R, years):
    y = np.array(R['year'])
    return np.array(y >= years[0]) & np.array(y <= years[1])


def f_rate_2026(theta):
    R = _run(theta)
    return float(np.mean(np.array(R['rate_new'])[_mask(R, (2025, 2026))]))


def f_waiting_end(theta):
    R = _run(theta)
    return float(R['UG'][-1])


def f_under_2026(theta):
    R = _run(theta)
    return float(np.mean(np.array(R['under'])[_mask(R, (2025, 2026))]))


FUNCS = dict(rate_2026=f_rate_2026, waiting_end=f_waiting_end, under_2026=f_under_2026)


def main(n, workers):
    res = dict(n=n, priors='broad behavioural ranges (not the fitted point)',
               provenance=MC.provenance(design='sobol', master=0), outcomes={})
    for k in OUTCOMES:
        idx, meta = MC.sobol_indices(FUNCS[k], PRIORS, n=n, master=0, boot=100, workers=workers)
        res['outcomes'][k] = dict(indices=idx, meta=meta, stiff=MC.stiff_directions(idx, 0.05))
    os.makedirs(OUT, exist_ok=True)
    json.dump(res, open(os.path.join(OUT, 'china_sobol.json'), 'w'), indent=1)
    L = ['# Which parameters move which China outcome: Sobol indices for the youth labour market', '',
         f"Generated by `python -m firms.china_sobol` ({n} base points, {n * (len(PRIORS) + 2):,} worlds per outcome, "
         'scrambled Sobol design, no simulation noise). Total-order index ST in brackets: [5-95% bootstrap]. '
         '**Bold** = stiff (ST at least 0.05). Priors are the broad behavioural ranges, not the fitted point.', '',
         '| Parameter | ' + ' | '.join(OUTCOMES) + ' |', '|---|' + '---:|' * len(OUTCOMES)]
    for p in PRIORS:
        cells = []
        for k in OUTCOMES:
            v = res['outcomes'][k]['indices'][p]
            c = f"S1 {v['S1']:.2f}, ST {v['ST']:.2f} [{v['ST_lo']:.2f}-{v['ST_hi']:.2f}]"
            cells.append(f'**{c}**' if v['ST'] >= .05 else c)
        L.append(f'| {LAB[p]} | ' + ' | '.join(cells) + ' |')
    L += ['', '## Stiff directions per outcome', '']
    for k in OUTCOMES:
        stiff = res['outcomes'][k]['stiff']
        L.append(f"- **{k}**: " + (', '.join(f"{LAB[p]} ({res['outcomes'][k]['indices'][p]['ST']:.2f})" for p in stiff)
                                   if stiff else 'none above the 0.05 threshold'))
    L += ['', 'Reading: the outcomes are printed in their own units (rate_new in %, waiting in millions, under in %). '
          'S1 summing well below 1 means interactions carry the outcome; a parameter outside every stiff list cannot '
          'be pinned down by these outcomes, so it stays a declared assumption. **Caveat:** at n=256 the estimates are '
          'tighter, but a few S1 point values still come out slightly negative (e.g. -0.01); that is estimator noise, '
          'not a share. Read the total-order ST and its bootstrap interval for the stiff/sloppy ordering.']
    open(os.path.join(OUT, 'china_sobol.md'), 'w').write('\n'.join(L) + '\n')
    print('\n'.join(L))


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('--n', type=int, default=256, help='base points, power of two (default 256)')
    ap.add_argument('--workers', type=int, default=6, help='worker processes (default 6)')
    a = ap.parse_args()
    main(a.n, a.workers)
