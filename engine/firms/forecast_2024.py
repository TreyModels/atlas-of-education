"""Strict forecast from a December 2024 cutoff (TODO §5 P1: graduation-season entry under the new NBS definition).

demand_inversion.py found that even with demand free the model misses the new-method seasonal shape (July jump ~4 pts
too large, spring 2-3 pts too low), because graduation-season entry was fitted on old-method data only. The new
definition starts in Dec 2023, so fitting it honestly requires a later cutoff. This script:
  * freezes data at Dec 2024 (Vintage with cutoff 2024-12; the 2025 graduating class, 12.22m, was announced in Nov 2024);
  * fits all parameters to old-method 2018-01..2023-06 AND new-method 2023-12..2024-12 (13 months);
  * forecasts Jan 2025 - Sep 2026 without refitting (verified months only);
  * compares with naive benchmarks that use the SAME definition: same calendar month of 2024, and 2024 mean.
Prespecified input rules after the cutoff are those of forecast_strict.py (demand = mean of last 12 months, graduates
trend after the announced class, entrants and property held).

Run from engine/:  python -m firms.forecast_2024 [--starts N]  -> firms/results/forecast_2024.{json,md}
"""
import argparse, json, math, os, sys
import numpy as np
from scipy.optimize import least_squares

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from firms import model as M, data_china as D, calibrate_china as C, forecast_strict as F

OUT = F.OUT
CUT = (2024, 12)


def run(theta, over=None):
    kw = dict(C.REF); kw.update({n: float(v) for (n, *_), v in zip(C.FREE, theta)}); kw.update(over or {})
    V = F.Vintage(cutoff=CUT, known_grad_years=1)
    ym = M.YouthMarket(V, **kw)
    ym.A = F.fill_demand(ym.A, CUT, 'last12')
    return ym.run()


def fit_pairs(R):
    old = F.obs_pairs(R, 2018, 2023, 'old')
    new = [x for x in F.obs_pairs(R, 2023, 2024, 'new', ('v',)) if (x[0], x[1]) <= CUT]
    return old, new


def resid(theta, w_new):
    R = run(theta)
    old, new = fit_pairs(R)
    r = [mod - ob for *_, ob, mod, _ in old] + [w_new * (mod - ob) for *_, ob, mod, _ in new]
    return np.array(r) if all(map(math.isfinite, r)) else np.full(len(r), 50.0)


def fit(nstarts, w_new, seed=5):
    lo = [f[1] for f in C.FREE]; hi = [f[2] for f in C.FREE]
    rng = np.random.default_rng(seed)
    starts = [np.array([f[3] for f in C.FREE])] + [rng.uniform(lo, hi) for _ in range(nstarts - 1)]
    best = None
    for s in starts:
        try:
            r = least_squares(resid, s, bounds=(lo, hi), diff_step=1e-3, max_nfev=300, args=(w_new,))
        except ValueError:
            continue
        if best is None or r.cost < best.cost:
            best = r
    return best


def test_pairs(R):
    return [x for x in F.obs_pairs(R, 2025, 2026, 'new', ('v',))]


def naive(kind):
    v24 = {m: D.youth(2024, m)[0] for m in range(1, 13)}
    mean24 = float(np.mean(list(v24.values())))
    return (lambda y, m: v24[m]) if kind == 'same_month_2024' else (lambda y, m: mean24)


def score_fn(f):
    pr = [(y, m, o[0], f(y, m), o[2]) for y in (2025, 2026) for m in range(1, 13)
          if (o := D.youth(y, m)) and o[1] == 'new' and o[2] == 'v']
    return C.stats(pr)


def seasonal(pairs):
    e = {}
    for y, m, ob, md, _ in pairs:
        e.setdefault(m, []).append(md - ob)
    return {m: float(np.mean(v)) for m, v in sorted(e.items())}


def main(nstarts):
    # weight on the 13 new-method months so they count as much as the 66 old-method months (sqrt(66/13) ~ 2.25)
    res = dict(cutoff=CUT, rows={})
    for lab, w in (('balanced weight on new-method months', math.sqrt(66 / 13)), ('equal weight per month', 1.0)):
        b = fit(nstarts, w)
        R = run(b.x)
        old, new = fit_pairs(R)
        tp = test_pairs(R)
        res['rows'][lab] = dict(w_new=w, params={n: float(v) for (n, *_), v in zip(C.FREE, b.x)},
                                at_bounds=[n for (n, lo, hi, _), v in zip(C.FREE, b.x) if min(v - lo, hi - v) < 1e-2 * (hi - lo)],
                                fit_old=C.stats(old), fit_new=C.stats(new), test=C.stats(tp),
                                seasonal_fit_new=seasonal(new), seasonal_test=seasonal(tp),
                                series={f"{y}-{m:02d}": [ob, md] for y, m, ob, md, _ in new + tp})
    res['naive_same_month_2024'] = score_fn(naive('same_month_2024'))
    res['naive_mean_2024'] = score_fn(naive('mean_2024'))
    json.dump(res, open(os.path.join(OUT, 'forecast_2024.json'), 'w'), indent=1)
    report(res)


def report(res):
    n1, n2 = res['naive_same_month_2024'], res['naive_mean_2024']
    L = ['# Strict forecast from a December 2024 cutoff', '',
         'Generated by `python -m firms.forecast_2024`. Data frozen at Dec 2024. Fitted to old-method 2018-01..2023-06 '
         'and new-method 2023-12..2024-12. Scored without refitting on verified new-method months Jan 2025 - Sep 2026. '
         'Both benchmarks use the new definition, so the comparison is like for like.', '',
         '| Version | Fit, old method | Fit, new method 2024 | Test MAE 2025-26 | Test bias | n |', '|---|---:|---:|---:|---:|---:|']
    for k, r in res['rows'].items():
        L.append(f"| Model, {k} | {r['fit_old']['mae']:.2f} | {r['fit_new']['mae']:.2f} | {r['test']['mae']:.2f} | "
                 f"{r['test']['bias']:+.2f} | {r['test']['n']} |")
    L += [f"| Naive: same month of 2024 | | | {n1['mae']:.2f} | {n1['bias']:+.2f} | {n1['n']} |",
          f"| Naive: 2024 mean | | | {n2['mae']:.2f} | {n2['bias']:+.2f} | {n2['n']} |", '']
    best = min(res['rows'].values(), key=lambda r: r['fit_new']['mae'])
    L += ['## Seasonal shape (model minus observed, pts, balanced-weight version)', '',
          '| Month | Fit 2024 | Test 2025-26 |', '|---:|---:|---:|']
    r = res['rows']['balanced weight on new-method months']
    for m in range(1, 13):
        a = r['seasonal_fit_new'].get(m, r['seasonal_fit_new'].get(str(m)))
        b = r['seasonal_test'].get(m, r['seasonal_test'].get(str(m)))
        L.append(f"| {m} | {'' if a is None else f'{a:+.1f}'} | {'' if b is None else f'{b:+.1f}'} |")
    L += ['', '## Monthly path, balanced-weight version (observed / model)', '', '| Month | Observed | Model |', '|---|---:|---:|']
    L += [f"| {k} | {v[0]:.1f} | {v[1]:.1f} |" for k, v in r['series'].items()]
    for k, rr in res['rows'].items():
        L += ['', f"**{k}**: " + ', '.join(f"{n} {v:.3g}" for n, v in rr['params'].items()) +
              f". At a bound: {', '.join(rr['at_bounds']) or 'none'}."]
    b = res['rows']['balanced weight on new-method months']
    nb = sum(len(rr['at_bounds']) for rr in res['rows'].values()) / len(res['rows'])
    L += ['', '## What this establishes', '',
          f"1. **The level is now right.** With the cutoff after the definition change, the test bias is {b['test']['bias']:+.2f} pts "
          'over 2025-26. Every Dec 2022 test missed by 4-6 pts in one direction.',
          f"2. **It still loses to naive:** {b['test']['mae']:.2f} against {n1['mae']:.2f} for the same month of 2024. The whole gap is "
          'seasonal amplitude. The model drains unemployment through spring too fast (about 2 pts too low, Mar-May) and '
          'adds the graduating class too abruptly in July (about 3 pts too high). The same pattern shows in the 2024 fit, '
          'so this is structural and not an error in the input forecasts.',
          f"3. **The fit is strained:** about {nb:.0f} of {len(C.FREE)} parameters sit at bounds, and wage speed lam_g swings from "
          '0.004 to 1 between weightings. The seasonal shape cannot be fitted within this structure. Candidates: (a) a '
          'stock of longer-term unemployed graduates whose job-finding does not rise in spring (duration dependence); '
          '(b) graduates entering the measured labour force over several months after July rather than at once (exam '
          'and postgraduate-application calendars); (c) new-definition counting of students who graduate mid-year. Each '
          'gives a different spring and July signature.']
    open(os.path.join(OUT, 'forecast_2024.md'), 'w').write('\n'.join(L) + '\n')
    print('\n'.join(L))


if __name__ == '__main__':
    ap = argparse.ArgumentParser(); ap.add_argument('--starts', type=int, default=6)
    main(ap.parse_args().starts)
