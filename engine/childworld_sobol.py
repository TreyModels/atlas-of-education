"""Global sensitivity of childworld (Sobol indices through mc.py): which structural parameters move which outcome?

First-order S1 is the share of an outcome's variance a parameter explains alone; total-order ST adds all its
interactions. Parameters with ST below 0.05 are 'sloppy' (the outcome does not care); the few above it are the 'stiff'
directions that the country matching can actually identify. The simulation seed is held fixed inside every evaluation,
so seed noise is not counted as parameter variance (its size is reported in childworld_mc_*.md).

Run from engine/:  python childworld_sobol.py [--n 1024] [--priors v2]  -> results/childworld_sobol.{json,md}
"""
import argparse, json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import childworld as W
import mc as MC

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'results')
OUTCOMES = ('oos_lower', 'cl', 'neither_share_oos', 'both_share_cl')
LAB = dict(y_med='income', w_child='child wage', farm='family farm/business', compat='work fits around school',
           v0='value of school', decay='value decline by level', cost='school cost', neither='value of neither (D)',
           girl_care="girls' care/marriage pull", haz='hazardous share 15-17')


# one function per outcome, defined at module level so they pickle
def f_oos_lower(theta): return 100 * W.simulate(theta, seed=0)['oos_lower']
def f_cl(theta): return 100 * W.simulate(theta, seed=0)['cl']
def f_neither(theta): return 100 * W.simulate(theta, seed=0)['neither_share_oos']
def f_both(theta): return 100 * W.simulate(theta, seed=0)['both_share_cl']


FUNCS = dict(oos_lower=f_oos_lower, cl=f_cl, neither_share_oos=f_neither, both_share_cl=f_both)


def main(n, version):
    pri = W.PRIORS if version == 'v1' else W.PRIORS_V2
    res = dict(n=n, priors=version, provenance=MC.provenance(design='sobol', master=0), outcomes={})
    for k in OUTCOMES:
        idx, meta = MC.sobol_indices(FUNCS[k], pri, n=n, master=0, boot=100)
        res['outcomes'][k] = dict(indices=idx, meta=meta, stiff=MC.stiff_directions(idx, 0.05))
    os.makedirs(OUT, exist_ok=True)
    json.dump(res, open(os.path.join(OUT, 'childworld_sobol.json'), 'w'), indent=1)
    L = ['# Which parameters move which outcome: Sobol indices for childworld', '',
         f"Generated by `python engine/childworld_sobol.py` ({n} base points, {n * (len(pri) + 2):,} worlds per outcome, priors {version}, "
         'scrambled Sobol design, fixed simulation seed). Total-order index ST in brackets: [5-95% bootstrap]. '
         '**Bold** = stiff (ST at least 0.05).', '',
         '| Parameter | ' + ' | '.join(OUTCOMES) + ' |', '|---|' + '---:|' * len(OUTCOMES)]
    for p in pri:
        cells = []
        for k in OUTCOMES:
            v = res['outcomes'][k]['indices'][p]
            c = f"S1 {v['S1']:.2f}, ST {v['ST']:.2f} [{v['ST_lo']:.2f}-{v['ST_hi']:.2f}]"
            cells.append(f'**{c}**' if v['ST'] >= .05 else c)
        L.append(f'| {LAB[p]} | ' + ' | '.join(cells) + ' |')
    L += ['', '## Stiff directions per outcome', '']
    for k in OUTCOMES:
        L.append(f"- **{k}**: " + ', '.join(f"{LAB[p]} ({res['outcomes'][k]['indices'][p]['ST']:.2f})" for p in res['outcomes'][k]['stiff']))
    L += ['', 'Reading: S1 summing well below 1 means interactions carry the outcome; ST much larger than S1 marks a parameter that '
          'matters only in combination. Parameters outside every stiff list cannot be pinned down by matching these outcomes.']
    open(os.path.join(OUT, 'childworld_sobol.md'), 'w').write('\n'.join(L) + '\n')
    print('\n'.join(L))


if __name__ == '__main__':
    ap = argparse.ArgumentParser(); ap.add_argument('--n', type=int, default=1024); ap.add_argument('--priors', default='v2', choices=['v1', 'v2'])
    a = ap.parse_args(); main(a.n, a.priors)
