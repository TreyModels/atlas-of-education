"""Global sensitivity of the Atlas household-and-school engine (Sobol indices through mc.py).

Which of the nine declared structural parameters move the Atlas engine's training outcomes? The priors are the
SPACE box recorded in history_match.py before the fitting search; the outcomes are model outputs on training rows
(so the sweep asks what the model makes of its own parameters, not what the data say).

Run from engine/:  python atlas_sobol.py [--n 64] [--workers 4] [--country cambodia]
                   -> results/atlas_sobol_{country}.{json,md}

Cost: one engine run per evaluation (~1 s), n*(d+2) evaluations per outcome.
"""
import argparse
import importlib
import json
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import mc as MC
from eduengine import ledger as LG

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'results')
COUNTRY = 'cambodia'
ANCHOR_UNTIL = 2015

# priors = the fitting box recorded in history_match.SPACE (kept in one place there)
import history_match as H
PRIORS = {k: (lo, hi, 'lin') for k, (lo, hi) in H.SPACE.items()}
LAB = {
    'kappa': "S2 value of a child's future income", 'poverty_line': 'S4 child-earnings need line',
    'h_max': 'S5 curriculum withholding', 'p_own': 'own-teacher tutoring price', 'p_firm': 'commercial tutoring price',
    'tut_effect': 'tutoring learning gain', 'r0': 'remedial demand', 'priv_quality': 'private-school quality premium',
    'priv_wage': 'private teachers’ wage',
}

# outcome = (indicator, year); values are model fractions -> percent
OUTCOMES = {
    'completion_upper_2010': ('completion_upper', 2010),
    'oos_lower_2015': ('oos_lower', 2015),
    'tutoring_g56_2015': ('tutoring_g56', 2015),
}


def _model_value(country, theta, indicator, year):
    C = importlib.import_module(f'countries.{country}')
    E = C.make(seed=0, anchor_until=ANCHOR_UNTIL, **theta)
    E.run()
    rows = LG.ledger(E, country, ANCHOR_UNTIL)
    for r in rows:
        if r['indicator'] == indicator and r['year'] == year:
            return 100.0 * float(r['model'])
    raise KeyError(f'{country}: no {indicator} row for {year}')


def f_completion_upper_2010(theta):
    return _model_value(COUNTRY, theta, *OUTCOMES['completion_upper_2010'])


def f_oos_lower_2015(theta):
    return _model_value(COUNTRY, theta, *OUTCOMES['oos_lower_2015'])


def f_tutoring_g56_2015(theta):
    return _model_value(COUNTRY, theta, *OUTCOMES['tutoring_g56_2015'])


FUNCS = dict(completion_upper_2010=f_completion_upper_2010, oos_lower_2015=f_oos_lower_2015,
             tutoring_g56_2015=f_tutoring_g56_2015)


def main(n, workers, country):
    global COUNTRY
    COUNTRY = country
    res = dict(n=n, country=country, priors='history_match.SPACE (the pre-registered fitting box)',
               provenance=MC.provenance(design='sobol', master=0), outcomes={})
    for k in OUTCOMES:
        idx, meta = MC.sobol_indices(FUNCS[k], PRIORS, n=n, master=0, boot=100, workers=workers)
        res['outcomes'][k] = dict(indices=idx, meta=meta, stiff=MC.stiff_directions(idx, 0.05))
    os.makedirs(OUT, exist_ok=True)
    base = f'atlas_sobol_{country}'
    json.dump(res, open(os.path.join(OUT, base + '.json'), 'w'), indent=1)
    L = [f'# Which parameters move the Atlas engine ({country}): Sobol indices', '',
         f"Generated by `python atlas_sobol.py --country {country}` ({n} base points, "
         f"{n * (len(PRIORS) + 2):,} engine runs per outcome, scrambled Sobol design, seed 0). Total-order index ST "
         'in brackets: [5-95% bootstrap]. **Bold** = stiff (ST at least 0.05). Priors are the fitting box recorded in '
         '`history_match.SPACE` before the search; outcomes are training-row model values (percent).', '',
         '| Parameter | ' + ' | '.join(OUTCOMES) + ' |', '|---|' + '---:|' * len(OUTCOMES)]
    for p in PRIORS:
        cells = []
        for k in OUTCOMES:
            v = res['outcomes'][k]['indices'][p]
            c = f"S1 {v['S1']:.2f}, ST {v['ST']:.2f} [{v['ST_lo']:.2f}-{v['ST_hi']:.2f}]"
            cells.append(f'**{c}**' if v['ST'] >= .05 else c)
        L.append(f'| {LAB[p]} | ' + ' | '.join(cells) + ' |')
    L += ['', '## Stiff directions per outcome', '']
    for k in OUTCOMES:
        stiff = res['outcomes'][k]['stiff']
        L.append(f"- **{k}**: " + (', '.join(f"{LAB[p]} ({res['outcomes'][k]['indices'][p]['ST']:.2f})" for p in stiff)
                                   if stiff else 'none above the 0.05 threshold'))
    L += ['', 'Reading: the outcomes are model values at training anchors, so a stiff parameter is one the country '
          'matching can in principle identify from these outcomes; a sloppy one is a declared assumption the record '
          'does not constrain. This is a statement about the model, not about Cambodia. **Caveat:** at n=64 some first-order S1 estimates fall outside [0, 1] (negative, or above 1); that is estimator noise, not a share. Read the total-order ST and its bootstrap interval for the stiff/sloppy ordering; do not read the S1 point values as variance shares at this n. A larger n (256+) is needed for precise shares.']
    open(os.path.join(OUT, base + '.md'), 'w').write('\n'.join(L) + '\n')
    print('\n'.join(L))


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('--n', type=int, default=64, help='base points, power of two (default 64)')
    ap.add_argument('--workers', type=int, default=4, help='worker processes (default 4)')
    ap.add_argument('--country', default='cambodia', choices=('cambodia', 'philippines', 'china'))
    a = ap.parse_args()
    main(a.n, a.workers, a.country)
