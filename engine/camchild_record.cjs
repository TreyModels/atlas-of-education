/* Pre-run the Cambodia child labour world: Monte Carlo bands for the curated scenarios.
   For each scenario and each seed, run the scenario and the no-policy baseline on the same draws (common random
   numbers). Store percentile bands of the child labour rate by year and region, and the share of seeds in which the
   scenario lowers national child labour. Writes web/data/camchild_runs.js (inlined into index.html by build_web.py).
   Run: node engine/camchild_record.cjs [seeds]      (30 seeds take about 90 seconds) */
'use strict';
const fs = require('fs'), path = require('path');
const E = require('../web/camchild.js');
const SCEN = require('../web/camchild_scenarios.js');
const SEEDS = +(process.argv[2] || 30);
const q = (a, p) => { const s = a.slice().sort((x, y) => x - y); const i = (s.length - 1) * p, lo = Math.floor(i), hi = Math.ceil(i); return s[lo] + (s[hi] - s[lo]) * (i - lo); };
const last4 = (R, g) => R.rows.slice(-4).reduce((s, x) => s + x[g].cl, 0) / 4;
const out = {seeds: SEEDS, N: 6000, made: new Date().toISOString().slice(0, 10), engine: 'camchild 0.1', scenarios: {}};
const t0 = Date.now();
for (const sc of SCEN) {
  const per = {pp: [], rural: [], all: []}, base = {pp: [], rural: [], all: []}, deltas = [];
  for (let s = 1; s <= SEEDS; s++) {
    const P = E.simulate({seed: s, policy: sc.p});
    const B = Object.keys(sc.p).length ? E.simulate({seed: s, policy: {}}) : P;
    for (const g of ['pp', 'rural', 'all']) { per[g].push(P.rows.map(x => x[g].cl)); base[g].push(B.rows.map(x => x[g].cl)); }
    deltas.push(last4(P, 'all') - last4(B, 'all'));
  }
  const band = M => M[0].map((_, t) => [.05, .25, .5, .75, .95].map(p => +q(M.map(r => r[t]), p).toFixed(5)));
  out.scenarios[sc.id] = {
    bands: {pp: band(per.pp), rural: band(per.rural), all: band(per.all)},
    baseMedian: {pp: band(base.pp).map(b => b[2]), rural: band(base.rural).map(b => b[2])},
    pLower: deltas.filter(d => d < -0.001).length / SEEDS,
    pHigher: deltas.filter(d => d > 0.001).length / SEEDS,
    delta: [.05, .5, .95].map(p => +q(deltas, p).toFixed(5)),
  };
  process.stdout.write(`${sc.id}: median change ${(100 * out.scenarios[sc.id].delta[1]).toFixed(2)} pts, lower in ${Math.round(100 * out.scenarios[sc.id].pLower)}% of seeds\n`);
}
const file = path.join(__dirname, '..', 'web', 'data', 'camchild_runs.js');
fs.writeFileSync(file, '/* generated by engine/camchild_record.cjs; do not edit */\nwindow.CamChildRuns = ' + JSON.stringify(out) + ';\n');
console.log('wrote', file, Math.round((Date.now() - t0) / 1000) + 's');
