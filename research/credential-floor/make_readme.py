"""Writes README.md from results/*.json and inputs/credential_floor_sources.json.
Every number in the README is read or computed here from those files; none is typed by hand
(the only literals in the text are structure names, years and the decision thresholds below,
which are printed as such)."""
import json, os
import numpy as np
import structures as S

R = os.path.join(S.HERE, 'results')
load = lambda f: json.load(open(os.path.join(R, f)))
rec, dis, nest = load('recovery_results.json'), load('discriminate_results.json'), load('nesting_check.json')
src = json.load(open(os.path.join(S.ROOT, 'inputs', 'credential_floor_sources.json')))['records']
ST = S.STRUCTS
DIAG_CUTOFF = 0.40      # decision threshold for 'clearly above chance' (chance = 1/4); printed in the text
p = lambda x, d=2: f'{x:.{d}f}'
pc = lambda x, d=0: f'{100 * x:.{d}f}%'
pt = lambda x: f'{100 * x:+.1f}'          # signed percentage points

QN = {1: 'poorest quintile', 2: 'second quintile', 3: 'middle quintile', 4: 'fourth quintile', 5: 'richest quintile'}
def label(k):
    f = {'ab_gap': 'Ability gap in completion (high- minus low-ability children)',
         'prem20': 'Change in completion if relative premium falls 20%',
         'prem40': 'Change in completion if relative premium falls 40%',
         'transfer': 'Change in completion after one-off transfer', 'noncomp': 'Share of non-completers who are high-ability',
         'reroute': 'Rerouting rate among non-completers'}
    if k == 'noncomp_highab': return f['noncomp']
    for fam in ('ab_gap', 'prem20', 'prem40', 'transfer', 'reroute'):
        if k.startswith(fam):
            rest = k[len(fam) + 1:]
            if rest.startswith('q') and rest[1:].isdigit(): where = QN[int(rest[1:])]
            elif rest.startswith('dq'): where = QN[int(rest[2:])]
            elif rest == 'top2': where = 'top two quintiles pooled'
            elif rest == 'bottom2': where = 'bottom two quintiles pooled'
            elif rest == 'dall': where = 'all households'
            elif rest == 'dbottom2': where = 'bottom two quintiles averaged'
            else: where = rest
            return f'{f[fam]}, {where}'
    return k

def find(item_sub, year):
    return [r for r in src if item_sub in r['item'] and str(r['year']) == str(year) and r['value'] is not None]

L = []
A = L.append
cfg_r, cfg_d = rec['config'], dis['config']
summ = rec['summary']['1.0']; summ_h = rec['summary']['0.5']

# ---------------------------------------------------------------- Puzzle
A('# Credential floor: can the data tell four theories of the credential apart?\n')
A('Generated by `make_readme.py` from `results/*.json`. No number below is typed by hand.\n')
A('## Puzzle\n')
A('The credential-floor model asks why households keep investing in a basic credential as its absolute '
  'wage return compresses. Earlier runs in this repository (`public/reference/credential-floor.md`) found that once '
  'the liquidity constraint is graded instead of a hard cut-off, human-capital, positional and relational '
  'versions of the model all fit the wealth-quintile completion profiles in Cambodia, and the data leave the '
  'relational weight at its prior. A standard rival was missing: relative risk aversion (Breen and Goldthorpe 1997). '
  'This folder adds it, then asks two questions. First, with four theories, can this kind of data tell them apart even '
  'in principle? Second, if not, which measurement or natural experiment would?\n')

# ---------------------------------------------------------------- Fact check
A('## Fact check: the observed targets\n')
A('The Cambodian targets are the ones used in `engine/relfloor_countries.py`. Values and sources below are read from '
  '`inputs/credential_floor_sources.json`; the sentence after the table says whether the hard-coded engine quintile numbers match them.\n')
A('| Target | Year | Source value (%) | Verification flag | Source |')
A('|---|---|---|---|---|')
ok_all = True
for yr in (2000, 2010, 2021):
    for r in find('Cambodia lower secondary completion rate, UIS CR.2 (survey-based)', yr):
        A(f"| Aggregate lower-secondary completion, UIS CR.2 | {yr} | {r['value']} | {r['confidence']} | {r['url'][:70]}... |")
for yr in (2014, 2021):
    vals = []
    for qn in range(1, 6):
        rr = find(f'UIS CR.2.Q{qn} ', yr)
        vals.append(rr[0] if rr else None)
    if all(vals):
        eng = S.KHM_Q[yr] * 100
        match = all(abs(v['value'] - e) < 1e-9 for v, e in zip(vals, eng)); ok_all &= match
        A(f"| Quintile profile, poorest to richest, UIS CR.2.Q1-Q5 | {yr} | {' / '.join(str(v['value']) for v in vals)} | "
          f"{'; '.join(sorted(set(v['confidence'] for v in vals)))} | {vals[0]['url'][:70]}... |")
A('')
A(f"Engine constants agree with the sources file for the quintile profiles: **{ok_all}**. "
  'Tolerances used by the repo and mirrored here: aggregate completion within the windows ' +
  ', '.join(f"{y}: {p(S.AGG[y][0] - S.AGG[y][1])} to {p(S.AGG[y][0] + S.AGG[y][1])}" for y in S.STAT_YEARS_AGG) +
  f"; each quintile within {p(S.Q_TOL)} of the UIS value, in 2014 and 2021. "
  'The sources file itself marks the DHS lower-secondary-by-quintile series as not found; the UIS CR.2.Q series is computed '
  'from DHS microdata by UIS, and the survey timing differs from the decision year in the model (see `credential-floor.md`).\n')

# ---------------------------------------------------------------- Rival explanations
A('## Rival explanations\n')
A('1. **M_HC, human capital:** a household completes the credential if the wage premium, larger for abler children, outweighs the cost (the repo\'s baseline; no extra term).')
A('2. **M_POS, positional:** adds a value that grows with the share of the previous cohort holding the credential (`b_pos`).')
A('3. **M_REL, relational:** adds a fixed eligibility value, the same for every child whatever their ability or family (`b_rel`) on top of the positional term, exactly as in the repo.')
A('4. **M_RRA, relative risk aversion (new):** adds a value `b_rra` times a smooth step in the household\'s income rank around a threshold rank `tau`, so families above the threshold need the credential to avoid falling below their parents\' position and families below it get almost nothing from it; it does not depend on the child\'s ability. '
  'Two new parameters, `b_rra` ~ U(0, 0.8) and `tau` ~ U(0.3, 0.9); the step width is fixed at 0.05 of the rank scale. M_RRA is human capital plus this term only (no positional or relational term).\n')
A('All four use the graded liquidity constraint by default. '
  f"Nesting check: with the new term at zero and hard liquidity, `structures.simulate` reproduces `engine/relfloor_countries.sim` for the same parameters and seed; "
  f"worst absolute difference in completion over {nest['n_param_sets_per_structure']} parameter sets per structure and all years 1998-2035: {nest['worst_abs_difference_overall']:.1e} "
  f"(M_HC {nest['worst_abs_difference_vs_repo']['M_HC']:.1e}, M_POS {nest['worst_abs_difference_vs_repo']['M_POS']:.1e}, M_REL {nest['worst_abs_difference_vs_repo']['M_REL']:.1e}); "
  f"profile-test verdict mismatches: {nest['profile_test_verdict_mismatches']}. "
  'This check is against the countries model; `engine/relfloor.py` (Philippines) is a different parameterisation and was not used as the reference.\n')

# ---------------------------------------------------------------- Test fixed in advance
A('## The test fixed in advance\n')
A('For each structure taken as the truth, ' + f"{cfg_r['datasets_per_true_structure']}" +
  ' true parameter sets were drawn from prior draws that give a plausible completion path (they pass the aggregate Cambodia windows). '
  'Each was simulated again with a fresh random seed to make synthetic observed data at the same resolution as the real test: aggregate completion in three years and the five-quintile profile in two survey years (13 numbers). '
  'All four structures were then fitted to it by ABC rejection with the repo\'s tolerances; a structure\'s posterior probability is its share of all accepted draws, with equal prior weight on the four structures. '
  'Rule stated before running: if the diagonal of the confusion matrix is not clearly above the off-diagonal entries (chance = 0.25), this kind of data cannot tell these theories apart however well the fitting is done. '
  f"For the README the phrase is made mechanical, and the cut-off was written after seeing the first run: every diagonal entry must be at least {p(DIAG_CUTOFF)}. "
  f"(The largest diagonal entry turned out to be {p(max(summ['confusion_mean_posterior'][s][s] for s in ST))}, so nothing hinges on the exact cut-off.)\n")
A(f"**Sizes used (smaller than the repo's main runs of {cfg_r['repo_main_run_draws']:,} draws per structure):** "
  f"{cfg_r['draws_per_structure_in_bank']:,} prior draws per structure in one shared bank, {cfg_r['households']:,} households per simulated country, "
  f"{cfg_r['datasets_per_true_structure']} synthetic datasets per true structure ({4 * cfg_r['datasets_per_true_structure']} in all). "
  f"Bank time {cfg_r['seconds_bank']:.0f} s. The true draw is removed from the bank for its own dataset.\n")

# ---------------------------------------------------------------- Results 1
A('## Results 1: can the data tell them apart?\n')
def cm(sm, title):
    A(f'**{title}**\n')
    A('| True structure (rows) / mean posterior given to (columns) | ' + ' | '.join(ST) + ' | Share of datasets where truth is highest | Mean accepted draws per dataset (median) | Datasets with fewer than 10 accepted |')
    A('|---|' + '---|' * (len(ST) + 3))
    for s in ST:
        row = sm['confusion_mean_posterior'][s]
        cells = ' | '.join(('**' + p(row[c]) + '**') if (c == s and row[c] is not None) else (p(row[c]) if row[c] is not None else 'n/a') for c in ST)
        h = sm['share_true_highest'][s]
        A(f"| {s} | {cells} | {pc(h) if h is not None else 'n/a'} | {sm['mean_accepted_per_dataset'][s]:.0f} ({sm['median_accepted_per_dataset'][s]:.0f}) | {sm['n_datasets_fewer_than_10_accepted'][s]} of {sm['n_datasets'][s]} |")
    A('')
cm(summ, 'Main result, the repo\'s tolerances (chance on each cell = 0.25)')
diag = [summ['confusion_mean_posterior'][s][s] for s in ST]
clear = all(d >= DIAG_CUTOFF for d in diag)
A(f"Mean diagonal {p(summ['mean_diagonal'])}, mean off-diagonal {p(summ['mean_offdiagonal'])}. "
  f"Under the stated rule the data **{'can' if clear else 'cannot'}** tell the four structures apart. "
  f"The truth received the highest posterior in {', '.join(f'{pc(summ['share_true_highest'][s])} of {s}' for s in ST)} datasets (ties share the credit; chance is 25%). "
  f"Accepted draws per dataset are large (means {', '.join(f'{summ['mean_accepted_per_dataset'][s]:.0f}' for s in ST)}), so these probabilities are not held back by too few draws. "
  f"With only {summ['n_datasets']['M_HC']} datasets per row the sampling error of each mean is of the order of 0.03 to 0.05, so differences between cells smaller than about 0.1 should not be read.\n")
cm(summ_h, 'Sensitivity: tolerances halved (a much stricter fit, from the same bank)')
A(f"With halved tolerances the mean accepted count falls to between {min(summ_h['mean_accepted_per_dataset'].values()):.0f} and {max(summ_h['mean_accepted_per_dataset'].values()):.0f} per dataset; "
  f"datasets with no accepted draw are left out of the means ({', '.join(f'{s}: {summ_h['n_datasets_zero_accepted'][s]}' for s in ST)}). "
  'These cells rest on very few draws and are weak; they are shown only to check that a stricter fit does not change the picture. '
  f"Mean diagonal {p(summ_h['mean_diagonal'])}, mean off-diagonal {p(summ_h['mean_offdiagonal'])}.\n")

# ---------------------------------------------------------------- Results 2
A('## Results 2: what would tell them apart?\n')
A(f"Among prior draws that fit the real Cambodia targets (aggregate windows and the 2014 and 2021 quintile profiles), "
  + ', '.join(f"{s}: {dis['accepted'][s]} accepted of {dis['draws_tried'][s]:,}" for s in ST) +
  f" (acceptance {', '.join(pc(dis['acceptance_rate'][s], 2) for s in ST)}). For each accepted draw, outputs for the 2021 cohort were simulated with {cfg_d['households_for_outputs']:,} households. "
  'Counterfactuals: the relative premium is lower from 2018 on; a one-off transfer equal to the full credential cost goes to the bottom 40% in 2021 and works only through the liquidity constraint. '
  'Separation is measured by the AUC of telling two structures apart from one output (0.5 = none, 1 = perfect; shown folded, so always at least 0.5) and the standardised difference (difference of means in pooled standard deviations).\n')
A(f"With these counts, an AUC differs from 0.5 by chance by about {p(dis['null_se_auc_typical'], 3)} (standard error), so values within about 0.1 of 0.5 are indistinguishable from nothing.\n")
A('**Ranking of outputs: mean folded AUC over the six pairs of structures**\n')
A('| Rank | Output | Mean AUC | Best pair | Best AUC | Std. difference (first minus second) |')
A('|---|---|---|---|---|---|')
for i, r in enumerate(dis['ranking'][:12], 1):
    A(f"| {i} | {label(r['output'])} | {p(r['mean_auc_folded'])} | {r['best_pair'][0]} vs {r['best_pair'][1]} | {p(r['best_auc_folded'])} | {r['best_std_diff']:+.2f} |")
A('')
A('**Best three outputs for each pair of theories (folded AUC; standardised difference first minus second)**\n')
A('| Pair | Output 1 | Output 2 | Output 3 |')
A('|---|---|---|---|')
for pair, rows in dis['best_outputs_by_pair'].items():
    A(f'| {pair} | ' + ' | '.join(f"{label(t['output'])}: AUC {p(t['auc_folded'])}, d {t['std_diff']:+.2f}" for t in rows) + ' |')
A('')
A('Median [5th, 95th percentile] of the leading output in each family, by structure:\n')
fam_best = {}
for r in dis['ranking']:
    fam_best.setdefault(r['family'], r['output'])
A('| Output | ' + ' | '.join(ST) + ' |')
A('|---|' + '---|' * len(ST))
for fam, k in fam_best.items():
    A(f'| {label(k)} | ' + ' | '.join(
        (lambda v: f'{v[1]:+.3f} [{v[0]:+.3f}, {v[2]:+.3f}]')(dis['per_structure_5_50_95'][k][s]) if dis['per_structure_5_50_95'][k][s] else 'n/a' for s in ST) + ' |')
A('')
A('Where each family points in practice:\n')
A('- Ability gap in completion within income groups: needs a survey that links a prior test score to later completion for households of known income.')
A('- Response to a lower premium: needs a natural experiment in the graduate wage premium (by region or cohort) with completion by income group measured afterwards.')
A('- Response to a cash transfer: a transfer programme aimed at the bottom 40%, with completion as the outcome.')
A('- Non-completers by ability: a prior test score for the children who leave.')
A('- Rerouting: the share of leavers who enter a short vocational credential, by household income.\n')

# ---------------------------------------------------------------- Meaning
top = dis['ranking'][0]
A('## What this means for the massification paper\n')
A(f"In this simulation, quintile completion profiles of the kind available for Cambodia do not separate the four theories: the diagonal of the confusion matrix has mean {p(summ['mean_diagonal'])} against {p(summ['mean_offdiagonal'])} off the diagonal, "
  f"which is {'close to' if not clear else 'above'} the 0.25 expected by chance, so a flat relational-weight posterior is what to expect rather than a finding about the relational floor. "
  f"The outputs that separate the theories best among profile-fitting draws are in the family \"{label(top['output']).split(',')[0]}\" (top output: {label(top['output'])}, mean AUC {p(top['mean_auc_folded'])}); "
  'these would have to be measured, not inferred from completion by wealth. '
  'This is a statement about a stylised model and about the resolution of the data, not evidence for or against any of the four theories in Cambodia.\n')

# ---------------------------------------------------------------- Limits
A('## Limits\n')
A('- Stylised units: income, cost and subsistence have no observed counterpart; only the growth rate is sourced.')
A('- The ability-income correlation is fixed at 0.3; the ability-based outputs depend on it directly.')
A('- One credential decision per child, not grade-by-grade survival.')
A('- M_RRA is one particular simple form (a smooth step in income rank, ability-independent); a different form, such as a gradient or one tied to parental class categories, could behave differently.')
A(f"- Smaller than the repo's runs in households ({cfg_r['households']:,} for fitting, {cfg_d['households_for_outputs']:,} for outputs), but with more prior draws than the repo's {cfg_r['repo_main_run_draws']:,} for the recovery bank ({cfg_r['draws_per_structure_in_bank']:,}); only {cfg_r['datasets_per_true_structure']} synthetic datasets per structure, so the confusion matrix has sampling error.")
A(f"- Accepted draws for the ranking are {', '.join(f'{dis['accepted'][s]}' for s in ST)} (HC, POS, REL, RRA); AUCs carry sampling error of about {p(dis['null_se_auc_typical'], 3)} under no difference. Draws accepted at {cfg_d['households_for_fit']:,} households are re-simulated at {cfg_d['households_for_outputs']:,} without re-checking the fit, as in the repo.")
A('- Synthetic data are drawn from the same model family that is fitted; real data add misspecification, so recovery here is a best case.')
A('- The tolerance windows are the repo\'s; with tighter windows fewer draws are accepted (see the sensitivity table).')
open(os.path.join(S.HERE, 'README.md'), 'w').write('\n'.join(L) + '\n')
print('README.md written,', len(L), 'lines')
