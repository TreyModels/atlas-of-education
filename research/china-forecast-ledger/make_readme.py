"""Write README.md from results/rolling_origin.json, ledger.csv and results/scoreboard.md. Numbers are never typed by hand:
every figure below is read from those files or from models.py. Re-run after evaluate.py / score.py.
"""
import csv, json, os
import models as M

R = json.load(open(os.path.join(M.HERE, 'results', 'rolling_origin.json')))
LEDGER = list(csv.DictReader(open(os.path.join(M.HERE, 'ledger.csv'))))
SB = open(os.path.join(M.HERE, 'results', 'scoreboard.md')).read().split('\n', 2)[2].strip()
H = R['horizons']; B = R['benchmark']; S = R['series']
f2 = lambda x: 'n/a' if x is None else f'{x:.2f}'

# ---- headline: which model-horizon cells beat the benchmark
cells = [(m, h, R['models'][m]['by_horizon'][str(h)]) for m in R['models'] if m != B for h in H]
cells = [c for c in cells if c[2]['n'] and c[2]['mean_diff'] != 0.0 or (c[2]['n'] and c[2]['wins'])]   # drop cells identical to the benchmark
better = [c for c in cells if c[2]['mean_diff'] < 0]
sig = [c for c in better if c[2]['t'] is not None and c[2]['t'] <= -2]
if not better:
    head = f"No forecaster had a lower mean absolute error than {B} at any horizon."
else:
    head = (f"No forecaster beat {B} across the board. In {len(better)} of {len(cells)} model-horizon comparisons the model had a lower mean "
            f"absolute error than {B}: " + '; '.join(f"{m} at {h} month{'s' if h > 1 else ''} (n = {c['n']}, mean difference {c['mean_diff']:+.2f}, t = {f2(c['t'])})" for m, h, c in better)
            + f". In the other {len(cells) - len(better)} it had a higher error or an identical one."
            if len(better) < len(cells) else f"Every forecaster had a lower mean absolute error than {B} in all {len(cells)} comparisons.")
sig_txt = (f"{len(sig)} of these comparisons has a paired t of -2 or lower." if sig else
           "None of the comparisons in the model's favour has a paired t of -2 or lower, so none is distinguishable from noise at this sample size.")

L = []
A = L.append
A('# Forecast ledger: China youth unemployment, small models against a naive benchmark')
A('')
A('*Generated by `make_readme.py` from `results/rolling_origin.json`, `ledger.csv` and `results/scoreboard.md`. Do not edit by hand.*')
A('')
A('## Puzzle')
A('')
A('Can a model with very few adjustable numbers forecast the official youth unemployment rate in China better than the rule '
  '"next month will look like the same month a year ago"? An earlier model in this repository (`engine/firms/`) had '
  f"{next(r['n_params'] for r in LEDGER if r['model'] == 'blind_seasonal_2024_spread11')} fitted parameters, and an internal review found it lost to that rule out of sample. "
  'This folder replaces it for research with a few small models, each explainable in a sentence or two, scored on many forecast '
  'origins, plus a public ledger of forecasts frozen before the data arrive.')
A('')
A('## Fact check')
A('')
A(f"The series is the National Bureau of Statistics (NBS) urban surveyed unemployment rate for ages 16-24, percent, monthly. It has two definitions:")
A('')
A(f"- Old method (students who are looking for work are counted): {R['old_method']['n']} months in the data file, {R['old_method']['first']} to {R['old_method']['last']}. The data file holds no old-method values after that.")
A(f"- New method (students excluded): from {S['first']} to {S['last']}. This is the only series used for evaluation, because the two definitions give different levels and are not comparable.")
A('')
A(f"The new-method series spans {S['n_calendar_span']} calendar months and holds {S['n_observed']} observations; "
  f"{', '.join(S['missing'])} {'is' if len(S['missing']) == 1 else 'are'} not in the data file. That is short: every number below rests on few forecasts, and the counts are given beside each number. "
  "The values are used exactly as stored in `engine/firms/data_china.py` (copied to `data/observed.csv`); they were not re-checked against NBS pages for this folder. "
  "Annual graduating-class sizes are the Ministry of Education's announced expected classes (`data/graduates.csv`).")
A('')
A('## Rival forecasters')
A('')
A('| Name | Estimated numbers | In plain words |')
A('|---|---:|---|')
for m, r in R['models'].items():
    A(f"| `{m}` | {r['n_params']} | {r['text']} |")
A('')
A('Each model is limited to four estimated numbers or fewer. The benchmark is `' + B + '`.')
A('')
A('## The test fixed in advance')
A('')
A(f"- Forecast origins: every observed month of the new-method series up to {R['last_origin']}. At each origin a model sees only data up to that month (tested in `test_ledger.py`).")
A(f"- Horizons: {', '.join(map(str, H))} months ahead. A forecast is scored only if the target month was observed.")
A(f"- Score: mean absolute error in percentage points, and for each model the paired difference against `{B}` on the same origin-target pairs "
  "(model absolute error minus benchmark absolute error; negative means the model was closer), the share of pairs the model won, and a paired t statistic.")
A('- Each model is compared on the pairs where both it and the benchmark can forecast, so the number of pairs differs between rows. '
  'Models that need more history start later.')
A('- The rule, the horizons and the benchmark were fixed before the results were produced. No model was tuned after seeing the scores.')
A('')
A('## Results')
A('')
A(head)
A('')
A(sig_txt)
A('')
A('| Model | Est. numbers | Horizon (months) | Pairs (n) | Model MAE | Benchmark MAE, same pairs | Mean difference | Model closer | Paired t |')
A('|---|---:|---:|---:|---:|---:|---:|---:|---:|')
for m, r in R['models'].items():
    for h in H:
        c = r['by_horizon'][str(h)]
        if not c['n']:
            A(f"| `{m}` | {r['n_params']} | {h} | 0 | | | | | |"); continue
        A(f"| `{m}` | {r['n_params']} | {h} | {c['n']} | {c['mae']:.2f} | {c['naive_mae']:.2f} | {c['mean_diff']:+.2f} | {c['wins']}/{c['n']} | {f2(c['t'])} |")
A('')
A(f"Notes on reading the table. The benchmark row compares itself with itself. `naive_last` at 12 months gives the same forecast as the benchmark by construction. "
  "Consecutive origins overlap, so pairs are not independent and the t statistics are, if anything, too optimistic. "
  "A blank or n/a t means fewer than three pairs or no variation.")
A('')
A('### Forecasts frozen for the ledger')
A('')
tg = sorted({r['target_month'] for r in LEDGER}); ms = []
for r in LEDGER:
    if r['model'] not in ms: ms.append(r['model'])
A('| Model | Date frozen | Data cutoff | ' + ' | '.join(tg) + ' |')
A('|---|---|---|' + '---:|' * len(tg))
for m in ms:
    rs = {r['target_month']: r for r in LEDGER if r['model'] == m}; r0 = next(iter(rs.values()))
    A(f"| `{m}` | {r0['date_frozen']} | {r0['data_cutoff']} | " + ' | '.join(rs[t]['forecast'] if t in rs else '' for t in tg) + ' |')
A('')
A('The two `blind_` rows were frozen earlier (5 November 2026) with an existing engine model and its own benchmark (the same month of 2024), and are copied from `engine/firms/results/blind_forecast_2026_11.json`. '
  'The other rows use data through ' + LEDGER[0]['data_cutoff'] + '. Where the reference month last year is missing from the data, the ledger note says the value was interpolated.')
A('')
A('### Scoreboard (new data scored against the ledger)')
A('')
A(SB)
A('')
A('## What this does and does not show')
A('')
A(f"It shows how often each small model came closer than `{B}` over the origins available, and by how much, on a series of {S['n_observed']} observations. "
  "It does not show that any model captures how the labour market works: a model that matches the seasonal pattern says nothing about causes. "
  f"The cohort model has two estimated numbers identified from {R['inflow']['distinct_classes_in_last_fit']} graduating classes ({R['inflow']['first_class']} to {R['inflow']['last_class']}) at the last origin, so its slope on cohort growth is weakly pinned down. "
  "Differences smaller than the error of the data series itself cannot be read as skill. The ledger is the real test: the forecasts were frozen before the months they predict were published.")
A('')
A('## How to add a new month and rescore')
A('')
A('1. Append one row to `data/observed.csv`: `year,month,rate,source_note` (rate in percent, new method; write where the number came from in `source_note`). When a new graduating class is announced, append it to `data/graduates.csv`.')
A('2. Run `python score.py`. It reads `ledger.csv` and `data/observed.csv`, refits nothing, and writes `results/scoreboard.md` and `results/scoreboard.csv`. With no new months it prints "nothing to score yet".')
A('3. Optionally re-run `python evaluate.py` and `python make_readme.py` to refresh the rolling-origin results and this page. `ledger.csv` is append-only; do not change frozen rows. New freezes should be added as new rows with their own freeze date and data cutoff.')
A('4. Run `python -m unittest test_ledger` to check the no-leak guard, the ledger rows and the scorer.')
A('')
A('## Limits')
A('')
A(f"- Short series: {S['n_observed']} observations, with {', '.join(S['missing'])} missing. The 12-month horizon rests on the fewest pairs.")
A('- Missing months inside the span are filled by straight-line interpolation only when a model reads them as a reference; scoring uses real observations only.')
A('- A graduating class is treated as known from December of the year before it graduates. This is an assumption about announcement timing that was not checked against the dates of the announcements.')
A('- Data values come from `engine/firms/data_china.py` as stored; their provenance flags are described there. They were not independently re-verified for this folder.')
A('- The new-method definition may change again; if it does, the series breaks and the ledger scores should say so.')
A('- Seasonal and cohort models fitted on about two years of data cannot tell a stable seasonal shape from a one-off pattern.')
A('- The earlier blind forecast was frozen with a different model, a different cutoff and a different benchmark, so it is scored against both its own benchmark and `' + B + '` in the scoreboard.')
open(os.path.join(M.HERE, 'README.md'), 'w').write('\n'.join(L) + '\n')
print('README.md written')
