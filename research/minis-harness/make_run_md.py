"""Writes records/<run_id>/RUN.md from run.json and outputs.json.

No phrase below is typed by hand about a particular run: every value is read from those two files,
and the fixed section text restates HARNESS.md's rules rather than describing results.
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent


def table(rows):
    return "\n".join("| " + " | ".join(str(c) for c in r) + " |" for r in rows)


def build(run_id):
    d = RECORDS / run_id
    rec = json.loads((d / "run.json").read_text(encoding="utf-8"))
    out = json.loads((d / "outputs.json").read_text(encoding="utf-8"))
    files = out["files"]

    L = []
    A = L.append
    A(f"# Run {rec['run_id']}\n")
    A("Generated by `make_run_md.py` from `run.json` and `outputs.json`. No number or count below is typed.\n")

    A("## Identity\n")
    A(table([("field", "value")] + [
        ("actor", rec["actor"]),
        ("operator", rec["operator"]),
        ("model", rec["model"] or "—"),
        ("harness", f"{rec['harness']} {rec['harness_version']}"),
        ("session", rec["session"] or "—"),
        ("started (UTC)", rec["started_utc"]),
        ("repo head", f"`{rec['repo_head']}`" if rec["repo_head"] else "—"),
        ("source digest", f"`{rec['source_digest']}`"),
    ]))
    A("")

    A("## Intent\n")
    A(f"{rec['intent']}\n")

    A("## Scope\n")
    A("\n".join(f"- `{s}`" for s in rec["scope"]))
    A("")

    A("## Network\n")
    A("\n".join(f"- {n}" for n in rec["network"]) if rec["network"] else "None declared.")
    A("")

    kinds = {}
    for f in files:
        kinds[f["kind"]] = kinds.get(f["kind"], 0) + 1
    A(f"## Files written ({len(files)})\n")
    if files:
        A(table([("path", "kind", "bytes", "sha256 (first 12)")] +
                [(f"`{f['path']}`", f["kind"], f["bytes"], f"`{f['sha256'][:12]}`") for f in files]))
    else:
        A("No file inside the declared scope changed. An empty run is a real result: it says the "
          "intent was attempted and left the tree untouched.")
    A("")
    A("Counts by kind: " + (", ".join(f"{k} {v}" for k, v in sorted(kinds.items())) if kinds else "none") + ".\n")

    A("## What this record does not establish\n")
    A("- That the output is correct. Hashes show the file is the one written, not that the number is right; "
      "`scripts/check-run-lifecycle.cjs` and the gate in `../GATE.md` still apply.")
    A("- That the model id is accurate. It is the operator's assertion; no weights or transcript are hashed here.")
    A("- That nothing happened outside `scope`. Files changed outside the declared scope are not hashed; "
      "`harness.py verify` cannot see them either.")
    if rec["notes"]:
        A(f"- Operator notes are unverified text: {rec['notes']}\n")
    return "\n".join(L).rstrip() + "\n"


def main(argv):
    if len(argv) not in (2, 3):
        raise SystemExit("usage: make_run_md.py <run_id> [records_dir]")
    run_id = argv[1]
    global RECORDS
    RECORDS = Path(argv[2]) if len(argv) == 3 else HERE / "records"
    text = build(run_id)
    (RECORDS / run_id / "RUN.md").write_text(text, encoding="utf-8")
    print(f"wrote {RECORDS / run_id / 'RUN.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
