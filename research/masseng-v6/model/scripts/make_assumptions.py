#!/usr/bin/env python3
"""Generate docs/assumptions.md and docs/facts_register.md from the country configs and the target builder,
so that no declared number is hand-typed in the documentation."""
import json, os, sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import masseng as m
from masseng import targets as T
from masseng.engine import DEFAULTS

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main(isos):
    L = ['# Declared assumptions (generated by scripts/make_assumptions.py — do not edit by hand)', '',
         'Every number below is DECLARED: chosen, with a source or a reason, and not fitted. Fitted parameters are listed in the',
         'results files. Costs are annual household costs of a school year as a share of GDP per head (fees, uniforms, transport,',
         'materials, forgone child earnings); only their ratios across levels and sectors and their dated changes are identified,',
         'because the overall scale is absorbed by the fitted cost coefficient.', '']
    L += ['## Engine defaults used when a country does not override them', '',
          '| parameter | value | role |', '|---|---|---|',
          f"| late entry share | {DEFAULTS['late']} | share of children starting Grade 1 a year after their planned age |",
          f"| repetition, primary | {DEFAULTS['rep_prim']} | yearly share repeating |",
          f"| repetition, secondary | {DEFAULTS['rep_sec']} | yearly share repeating |", '']
    for iso in isos:
        c = m.Country(iso)
        cfg = c.config
        L += [f"## {cfg['country']} ({iso})", '']
        L += ['**Years:** simulate {simulate_from}–{simulate_to}; train {train[0]}–{train[1]}; test {test[0]}–{test[1]}.'.format(**cfg['years']), '']
        st = cfg['structure']
        L += ['**Structure:** ' + ', '.join(f'{k} = {v}' for k, v in st.items() if not k.startswith('_')), '']
        if st.get('_note'):
            L += [f"> {st['_note']}", '']
        if 'upper_secondary_note' in st:
            L += [f"> {st['upper_secondary_note']}", '']
        L += ['**Costs (share of GDP per head):**', '', '| level | public | private |', '|---|---|---|']
        for lev, v in cfg['costs_share_of_gdppc'].items():
            if lev.startswith('_'):
                continue
            L.append(f"| {lev} | {v['public']} | {v['private']} |")
        L += ['', f"> {cfg['costs_share_of_gdppc'].get('_note', '')}", '']
        L += ['**Dated policy events (cost changes):**', '', '| year | level | sector | change | what |', '|---|---|---|---|---|']
        for ev in cfg.get('policy_events', []):
            L.append(f"| {ev['year']} | {ev['level']} | {ev['sector']} | {ev['cost_change']:+} | {ev['what']} |")
        for tr in cfg.get('transfers', []):
            L.append(f"| {tr['year']} (ramp {tr.get('ramp_years', 1)}y) | {', '.join(tr['levels'])} | deciles {', '.join(str(d + 1) for d in tr['deciles'])} | −{tr['value']} | {tr['what']} |")
        L += ['', '**Entry age:** share starting Grade 1 at age 6: ' +
              ', '.join(f'{k}: {v}' for k, v in cfg['entry_age']['share_at_6'].items() if not k.startswith('_')) +
              '. ' + cfg['entry_age'].get('_note', ''), '']
        for key in ('repetition', 'catch_up_entry', 'tertiary_entry_exam', 'wdi_repairs', 'demography'):
            if key in cfg:
                L += [f'**{key}:** `' + json.dumps({k: v for k, v in cfg[key].items() if not str(k).startswith('_')}) + '`', '']
                note = cfg[key].get('_note') if isinstance(cfg[key], dict) else None
                if note:
                    L += [f'> {note}', '']
        tc = cfg['tertiary_public_capacity']
        L += [f"**Tertiary public capacity rule:** {tc['rule']} (anchor {tc.get('anchor_year')}).", '']
    open(os.path.join(ROOT, 'docs', 'assumptions.md'), 'w').write('\n'.join(L) + '\n')

    F = ['# Facts register (generated by scripts/make_assumptions.py)', '',
         'Each observed number used anywhere, with its role. Roles follow the Atlas facts-register rule: a fact moves from Test to',
         'Calibration only with a dated entry, and never back. Train = used to fit; Test = never used to fit; Diagnostic = observed',
         'but neither fitted nor scored (e.g. conflicting sources, or outside the scored series).', '']
    for iso in isos:
        c = m.Country(iso)
        rows = T.build(c)
        F += [f"## {c.config['country']}", '', '| series | years | n | role | source |', '|---|---|---|---|---|']
        groups = {}
        for r in rows:
            groups.setdefault((r['series'], r['role'], r['source']), []).append(r['year'])
        for (s, role, src), ys in sorted(groups.items()):
            F.append(f"| {s} | {min(ys)}–{max(ys)} | {len(ys)} | {role} | {src} |")
        moved = c.config.get('targets', {}).get('income_gradient_2019', {}).get('_moved')
        if moved:
            F += ['', f'Dated move: {moved}']
        F.append('')
    open(os.path.join(ROOT, 'docs', 'facts_register.md'), 'w').write('\n'.join(F) + '\n')
    print('wrote docs/assumptions.md and docs/facts_register.md')


if __name__ == '__main__':
    main(sys.argv[1:] or ['PHL', 'KHM'])
