#!/usr/bin/env python3
"""Write README.md from the result files (no hand-typed numbers)."""
import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
J = lambda *p: json.load(open(os.path.join(ROOT, *p)))
REPORTED = 'income|unconstrained'


def table(scores, key):
    t = scores[key]['table']
    lines = ['| series | n | model | naive: last value | naive: trend | beats both |', '|---|---|---|---|---|---|']
    wins = nb = 0
    for s, v in t.items():
        has = v['persistence'] == v['persistence']
        win = has and v['model'] < min(v['persistence'], v['trend'])
        wins += win; nb += has
        f = lambda x: f'{x:.2f}' if x == x else '—'
        lines.append(f"| {s} | {v['n']} | {f(v['model'])} | {f(v['persistence'])} | {f(v['trend'])} | "
                     f"{'yes' if win else ('no' if has else 'no benchmark')} |")
    return lines, wins, nb


def main():
    L = ['# masseng — a portable cohort model of education massification', '',
         '*Generated by `scripts/make_readme.py` from the result files. Do not edit numbers by hand.*', '',
         'A cohort-flow model of a national school system: births → Grade 1 → primary, secondary (with optional upper',
         'secondary from a reform year) → tertiary, by income decile and public/private provider. Indicators are computed',
         'with the official age bands and durations published for each year. Country facts live in `countries/<ISO3>/`;',
         'the engine holds none. See `docs/model.md` (what the code does), `PROTOCOL.md` (pre-registered test and dated',
         'amendments), `docs/assumptions.md` (every declared number), `docs/facts_register.md` (every observed number and',
         'its role).', '']
    for iso, ver in (('PHL', 'v3'), ('PHL', 'v1'), ('KHM', 'v3')):
        p = os.path.join(ROOT, 'outputs', iso, ver, 'scores.json')
        if not os.path.exists(p):
            continue
        sc = json.load(open(p))
        if REPORTED not in sc:
            continue
        lines, w, nb = table(sc, REPORTED)
        status = {('PHL', 'v3'): 'reported specification, test inspected (PROTOCOL A2–A5)',
                  ('PHL', 'v1'): 'pre-registered specification, first scored result',
                  ('KHM', 'v3'): 'port; supply rule fixed from the Philippine result before fitting'}[(iso, ver)]
        L += [f'## {iso} {ver} — {status}', '',
              f'**Loss first:** the model beats both naive benchmarks on {w} of {nb} benchmarked held-out series.', '']
        L += lines
        L += ['', 'All fitted rivals (demand|supply), mean held-out RMSE on the three GERs (training loss in brackets):', '']
        for k, v in sc.items():
            L.append(f"- `{k}`: {v['mean_test_rmse_ger']:.2f} ({v['train_cost']:.1f})")
        L.append('')
    v5p = os.path.join(ROOT, 'outputs', 'PHL', 'v5', 'scores.json')
    if os.path.exists(v5p):
        from make_report5 import markdown_block
        scores5 = json.load(open(v5p))
        recovery5p = os.path.join(ROOT, 'outputs', 'PHL', 'v5', f"recovery_{scores5['winner_by_preregistered_rule']}.json")
        recovery5 = json.load(open(recovery5p)) if os.path.exists(recovery5p) else None
        L += markdown_block(scores5, recovery5)
    rp = os.path.join(ROOT, 'outputs', 'PHL', 'recovery.json')
    if os.path.exists(rp):
        r = json.load(open(rp))
        L += ['## Recovery test (PHL v3)', '', f"Rule: {r['rule']}. **Accepted: {r['accepted']}** ({r['replicates']} replicates).", '',
              '| parameter | truth | median recovered | 10th–90th pct | share within ±25% |', '|---|---|---|---|---|']
        for n, v in r['params'].items():
            w = '—' if v['within25'] is None else f"{v['within25']:.2f}"
            L.append(f"| {n} | {v['truth']:.3f} | {v['median']:.3f} | {v['p10']:.2f} – {v['p90']:.2f} | {w} |")
        L.append('')
    L += ['## Reproduce', '', '```', 'python3 tests/test_model.py                       # invariants: conservation, timing, protocol',
          'python3 scripts/fit_rivals.py PHL v3               # fit the six rivals on 1971–1995 (≈15 min, 2 cores)',
          'python3 scripts/score_rivals.py PHL v3             # held-out scores and benchmarks',
          'python3 scripts/recovery_test.py PHL outputs/PHL/v3/fit_income_unconstrained.json 20',
          'python3 scripts/fit_one.py KHM v3 income unconstrained && python3 scripts/score_rivals.py KHM v3',
          'python3 scripts/make_figures.py PHL v3 "income|unconstrained"',
          'python3 scripts/make_assumptions.py && python3 scripts/make_readme.py', '```', '',
          'Requires Python 3.10+, numpy, scipy, matplotlib. Runs are deterministic. Data: World Bank WDI (fetched',
          '2026-11-21, transcribed into `countries/*/wdi_series.json`), CHED, DepEd, PIDS, press reports of MoEYS pass rates.', '',
          'Credit: built for Dr Trey Menefee\'s Atlas of Education programme; follows its GATE.md research standards.', '']
    open(os.path.join(ROOT, 'README.md'), 'w').write('\n'.join(L) + '\n')
    print('README.md written')


if __name__ == '__main__':
    main()
