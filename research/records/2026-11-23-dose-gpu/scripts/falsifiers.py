"""Tests designed to kill the finding, using the fitted populations (no further fitting needed).

F1 parameter recovery: do the fitted 90% intervals contain the values that generated the synthetic data
   this project's recovery datasets were built from (kin strength 2.2, downward-flow 2.5, cohort
   deepening 1.0, career delay 3.0, pickiness 2.0)?
F2 scenario recovery: synthetic observations generated from known A parameters and from known B
   parameters are fitted by BOTH the A and the B posterior.  The mechanism is credible only if the data
   generated by a scenario is better predicted by that scenario's posterior.
F3 permutation: the same posterior is asked to predict the real schooling allocation and an allocation
   with cell-level schooling shares permuted within country-cohort.  If the dose channel is real the
   real allocation should be predicted better.
usage: falsifiers.py --dir results [--n 150] [--procs 6]
"""
import json, os, sys, argparse
import numpy as np
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import model as M
from multiprocessing import Pool

ap = argparse.ArgumentParser()
ap.add_argument("--dir", default="../results"); ap.add_argument("--panel", default="data/panel.json")
ap.add_argument("--n", type=int, default=150); ap.add_argument("--procs", type=int, default=6)
ap.add_argument("--what", default="all")
a = ap.parse_args()
D = a.dir
PAN = json.load(open(a.panel)); FIT, HOLD = PAN["FIT"], PAN["HOLD"]
TRUTH = {s: json.load(open(f"data/truth_{s}.json")) for s in "AB"}
REPORT = ["th_k", "th_f", "kappa", "gam", "lam_s"]


def load(s):
    p = os.path.join(D, f"cpu_fit{s}.json")
    return json.load(open(p)) if os.path.exists(p) else None


def posterior(fit):
    u = np.array(fit["u"]); w = np.array(fit["w"]); th = np.array(fit["lo"]) + u * (np.array(fit["hi"]) - np.array(fit["lo"]))
    out = {}
    for k, n in enumerate(fit["names"]):
        i = np.argsort(th[:, k]); c = np.cumsum(w[i]) / w.sum()
        out[n] = dict(q05=float(np.interp(.05, c, th[i, k])), q50=float(np.interp(.5, c, th[i, k])),
                      q95=float(np.interp(.95, c, th[i, k])))
    return out


def particles(fit, n, rng):
    u = np.array(fit["u"]); w = np.array(fit["w"]); idx = rng.choice(len(w), n, p=w)
    return np.array(fit["lo"]) + u[idx] * (np.array(fit["hi"]) - np.array(fit["lo"])), np.array(fit["f"])[idx]


def job_scen(args):
    scen, P, f, seed, iso, obs = args
    pc = dict(PAN["countries"][iso]); pc.update(obs)
    S = M.summaries(M.simulate(pc, P, 0 if scen == "A" else 1, seed, f, nW=24))
    d, _ = M.distance(S, pc)
    return scen, iso, d


def job_perm(args):
    seq, P, f, seed, iso, alt = args
    pc = dict(PAN["countries"][iso])
    if alt: pc["shF"] = PERM[iso]["shF"]; pc["shM"] = PERM[iso]["shM"]
    S = M.summaries(M.simulate(pc, P, 0 if seq == "A" else 1, seed, f, nW=24))
    d, _ = M.distance(S, pc); return seq, iso, alt, d


if __name__ == "__main__":
    A, B = load("A"), load("B"); R = {}
    rng = np.random.default_rng(21)
    # ---------------- F1 parameter recovery against the truth used by this project
    if a.what in ("recover", "all") and A:
        post = posterior(A); R["F1_parameter_recovery"] = {}
        for s in "AB":
            th = TRUTH[s]["theta"]
            for n in REPORT:
                k = A["names"].index(n); tv = float(th[k]); d = post[n]
                R["F1_parameter_recovery"].setdefault(s, {})[n] = dict(
                    truth=tv, q05=d["q05"], q50=d["q50"], q95=d["q95"],
                    covered=bool(d["q05"] <= tv <= d["q95"]))
        print("F1 (A posterior vs known truths):", json.dumps(R["F1_parameter_recovery"]["A"], indent=1), flush=True)
    # ---------------- F2 scenario recovery on synthetic data from known parameters
    if a.what in ("scenario", "all") and A and B:
        pool = Pool(a.procs); out = {}
        for truth in "AB":
            tr = TRUTH[truth]; th = np.array(tr["theta"]); sc = 0 if tr["scen"] == "A" else 1
            r2 = np.random.default_rng(tr["seed"]); OBS = {}
            for iso in FIT:                      # generate the synthetic observations once
                pc = PAN["countries"][iso]
                S = M.summaries(M.simulate(pc, th, sc, int(r2.integers(1e9)), tr["f"][iso], nW=40))
                OBS[iso] = {}
                for g, key, sd in (("tfr", "tfr", .10), ("asfr", "asfr1519", .004), ("smam", "smam", .4), ("m18", "m18", .015)):
                    OBS[iso][key] = {y: float(S[g][int(y)] + r2.normal(0, sd))
                                     for y in pc[key] if not np.isnan(S[g].get(int(y), np.nan))}
            parts = {s: particles(f, a.n, np.random.default_rng(31 + ord(s))) for s, f in (("A", A), ("B", B))}
            jobs = [(s, parts[s][0][i], parts[s][1][i][FIT.index(iso)], 5000 + i, iso, OBS[iso])
                    for s in ("A", "B") for i in range(a.n) for iso in FIT]
            res = pool.map(job_scen, jobs, chunksize=4)
            out[truth] = {s: float(np.mean([d for (ss, iso, d) in res if ss == s])) for s in ("A", "B")}
            bA = np.array([[d for (ss, iso, d) in res if ss == s and iso == i] for s in ("A",) for i in FIT])
            bB = np.array([[d for (ss, iso, d) in res if ss == s and iso == i] for s in ("B",) for i in FIT])
            diff = bA.mean(1) - bB.mean(1)
            boot = [np.mean(rng.choice(diff, len(diff))) for _ in range(2000)]
            out[truth]["diff_A_minus_B"] = float(diff.mean())
            out[truth]["diff_ci"] = [float(np.quantile(boot, .025)), float(np.quantile(boot, .975))]
            out[truth]["right_scenario_wins"] = bool((diff.mean() < 0) if truth == "A" else (diff.mean() > 0))
        pool.close(); pool.join()
        R["F2_scenario_recovery"] = out
        print("F2:", json.dumps(out, indent=1), flush=True)
    # ---------------- F3 permutation of the schooling allocation
    if a.what in ("permute", "all") and A:
        PERM = {}
        for iso in FIT + HOLD:
            pc = PAN["countries"][iso]
            shF = np.array(pc["shF"]); shM = np.array(pc["shM"])
            perm = np.random.default_rng(77).permutation(10)     # permute the 2x5 urban x wealth cells
            shF2 = shF.reshape(14, 10, 7)[:, perm, :].reshape(14, 10, 7); shM2 = shM.reshape(14, 10, 7)[:, perm, :].reshape(14, 10, 7)
            PERM[iso] = dict(shF=shF2.tolist(), shM=shM2.tolist())
        globals()["PERM"] = PERM
        parts = particles(A, a.n, np.random.default_rng(41))
        jobs = [("A", parts[0][i], parts[1][i][FIT.index(iso)], 7000 + i, iso, alt)
                for i in range(a.n) for iso in FIT + HOLD for alt in (False, True)]
        pool = Pool(a.procs); res = pool.map(job_perm, jobs, chunksize=4); pool.close(); pool.join()
        o = {}
        for lab, alt in (("real", False), ("permuted", True)):
            for region, isos in (("fit", FIT), ("holdout", HOLD)):
                o[f"{lab}_{region}"] = float(np.mean([d for (s, iso, al, d) in res if al == alt and iso in isos]))
        R["F3_permutation"] = o
        print("F3:", json.dumps(o, indent=1), flush=True)
    json.dump(R, open(os.path.join(D, "falsifiers.json"), "w"), indent=1, default=float)
    print("wrote", os.path.join(D, "falsifiers.json"))
