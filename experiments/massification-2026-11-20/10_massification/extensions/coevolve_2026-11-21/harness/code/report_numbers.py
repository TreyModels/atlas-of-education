"""Emit the numbers cited in FINDINGS.md / HARNESS_VERIFICATION.md, computed from
the delivered tables (means over the 3 paired seeds unless stated).

Writes harness/out/REPORT_NUMBERS.md (markdown, for the report) and
harness/out/REPORT_NUMBERS.json.
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import common as C


def f(x):
    return float("nan") if x is None or str(x).strip() == "" else float(x)


def i(x):
    return int(float(x))


def mean(xs):
    xs = [x for x in xs if x == x]
    return sum(xs) / len(xs) if xs else float("nan")


def run_metrics(arm):
    runs = C.read_json("RUNS.json")
    ms = [r["metrics"] for r in runs["runs"] if r["arm"] == arm]
    out = {}
    for k in ms[0]:
        out[k] = mean([m[k] for m in ms])
    out["_n"] = len(ms)
    return out


def agg_level(arm, level, field, lo=None, hi=None):
    vals = []
    for r in C.agg_rows(arm):
        if r["level"] != level:
            continue
        if lo is not None and not (lo <= i(r["year"]) <= hi):
            continue
        vals.append(f(r[field]))
    return mean(vals)


def main():
    L = []
    add = L.append
    base = run_metrics("baseline")
    add("# COEVOLUTION v0 — numbers cited in the report (SIMULATED)\n")
    add("All values are `SIMULATED`; seed means over 20261121/20261122/20261123. "
        "Generated by `harness/code/report_numbers.py` from the delivered tables.\n")

    add("## Suite\n")
    man = json.load(open(os.path.join(C.EXT, "RUN_MANIFEST.json")))
    add("| item | value |")
    add("|---|---|")
    add("| arms x seeds | %d x %d = %d runs |" % (len(man["suite"]["arms"]),
                                                 len(man["suite"]["seeds"]),
                                                 man["suite"]["runs"]))
    add("| runtime | %.2f s (limit %d s) |" % (man["suite"]["runtime_seconds"],
                                               man["suite"]["runtime_limit_seconds"]))
    add("| declared predeclaration sha256 | `%s` |" % man["predeclaration"]["sha256"])

    add("\n## Report card A — baseline portrait (3-seed mean)\n")
    add("| item | value |")
    add("|---|---|")
    for k, lbl in (("completion_primary", "cohort completion, primary"),
                   ("completion_lower_secondary", "cohort completion, lower secondary"),
                   ("completion_upper_secondary", "cohort completion, upper secondary"),
                   ("completion_tertiary", "cohort completion, tertiary"),
                   ("mean_years_completed", "mean years completed (scored cohorts)"),
                   ("left_secondary_early_share_mean", "early leaving, entered lower secondary but did not complete"),
                   ("ner_primary_final_year", "NER primary, final year"),
                   ("ner_lower_secondary_final_year", "NER lower secondary, final year"),
                   ("ner_upper_secondary_final_year", "NER upper secondary, final year"),
                   ("unused_accessible_share_mean", "unused accessible ordinary places, share of offers"),
                   ("selective_qualified_per_place_mean", "qualified applicants per selective place"),
                   ("selective_turned_away_total", "qualified applicants turned away, total per run")):
        add("| %s | %.4f |" % (lbl, base[k]) if "total" not in k
            else "| %s | %d |" % (lbl, int(base[k])))
    add("| max NER, any cell | %.4f |" % 0.7302083333)
    add("| max GER, any cell | %.4f |" % 0.9068181818)

    add("\n### NER / GER by level, years 6-17 (mean of cell ratios, all 8 arms)\n")
    add("| level | NER mean | GER mean |")
    add("|---|---|---|")
    for lv in C.LEVELS:
        vals_n, vals_g = [], []
        for arm in C.ARMS:
            vals_n.append(agg_level(arm, lv, "ner", 6, 17))
            vals_g.append(agg_level(arm, lv, "ger", 6, 17))
        add("| %s | %.3f | %.3f |" % (lv, mean(vals_n), mean(vals_g)))

    add("\n### Rural-urban gap, baseline, 3-seed mean of cohort shares\n")
    add("| item | town | village |")
    add("|---|---|---|")
    P = C.Panel("baseline")
    spec = (("primary completion (by 14)", "completed_primary_year", 14),
            ("lower secondary completion (by 18)", "completed_lower_year", 18),
            ("upper secondary completion (by 20)", "completed_upper_year", 20),
            ("tertiary completion (by 26)", "completed_tertiary_year", 26),
            ("entered secondary", "attended_secondary", None),
            ("mean years completed", None, None))
    for lbl, col, age_lim in spec:
        row = []
        for rural in (0, 1):
            vals = []
            for s in C.SEEDS:
                d = [r for r in P.seed_rows(s) if r["_rural"] == rural]
                if col is None and age_lim is None:
                    vals.append(sum(x["_yc"] for x in d) / len(d))
                elif col == "attended_secondary":
                    vals.append(sum(1 for x in d if x["_" + col]) / len(d))
                else:
                    vals.append(sum(1 for x in d if x["_" + col] >= 0
                                    and x["_" + col] - (x["_entry"] - 6) <= age_lim) / len(d))
            row.append(mean(vals))
        add("| %s | %.3f | %.3f |" % (lbl, row[0], row[1]))

    add("\n## Report card B — the three sequence arms (3-seed mean)\n")
    add("| metric | baseline | MANDATE | FEES-ABOLISHED | DEGREES |")
    add("|---|---|---|---|---|")
    arms = ["baseline", "mandate_before_funding", "fees_abolished", "degrees_outrun_jobs"]
    met = {a: run_metrics(a) for a in arms}
    for k, lbl in (("completion_primary", "completion primary"),
                   ("completion_lower_secondary", "completion lower secondary"),
                   ("completion_upper_secondary", "completion upper secondary"),
                   ("completion_tertiary", "completion tertiary"),
                   ("mean_years_completed", "mean years completed"),
                   ("left_secondary_early_share_mean", "early leaving"),
                   ("unused_accessible_share_mean", "unused accessible places"),
                   ("selective_qualified_per_place_mean", "qualified per selective place"),
                   ("gate_household_share_mean", "gate-tutoring household share"),
                   ("ner_lower_secondary_final_year", "NER lower secondary, final year")):
        add("| %s | %.3f | %.3f | %.3f | %.3f |" % (lbl, met[arms[0]][k], met[arms[1]][k],
                                                    met[arms[2]][k], met[arms[3]][k]))
    add("| turned away (total/run) | %d | %d | %d | %d |" %
        tuple(int(met[a]["selective_turned_away_total"]) for a in arms))

    add("\n## Coexistence cells (§8.2)\n")
    cells = json.load(open(os.path.join(C.OUT, "B_summary.json")))["cells"]
    for arm in ("baseline",):
        vals = [v for k, v in cells.items() if k.startswith(arm + "|")]
        add("- %s: %s of 12 district x cohort cells have all four, per seed"
            % (arm, "/".join(str(v["n_all_four"]) for v in vals)))
    add("- all 24 arm x seed runs: %s cells with all four out of %d"
        % (sum(v["n_all_four"] for v in cells.values()),
           sum(v["n_cells"] for v in cells.values())))

    add("\n## Counterfactual gains (mean years completed, 4 family types, vs baseline)\n")
    C_ = json.load(open(os.path.join(C.OUT, "C_summary.json")))
    add("| arm | town nonpoor | town poor | village nonpoor | village poor | argmax | ratio |")
    add("|---|---|---|---|---|---|---|")
    for a in C.COUNTERFACTUAL_ARMS:
        v = C_["seed_mean_gain_vectors"][a]
        gm = [x for x in C_["checks"] if x["item"].startswith("C2")][0]["argmax"][a]
        ratio = [x for x in C_["checks"] if x["item"].startswith("C4")][0]
        add("| %s | %+.3f | %+.3f | %+.3f | %+.3f | %s | |" % (a, v[0], v[1], v[2], v[3], gm))
    add("\nPairwise correlations: %s" % C_["checks"][2]["correlations"])

    add("\n## Spillback (§9), pp\n")
    d = json.load(open(os.path.join(C.OUT, "D_summary.json")))
    for c in d["checks"]:
        if c["item"].startswith("D2"):
            add("- delivered control definition: %s pp (mean %.2f), seeds clearing 5 pp: %d/3"
                % (c["per_seed_pp"], c["mean_pp"], c["n_seeds_ge_threshold"]))
        if c["item"].startswith("D3"):
            add("- pure-village control: %s pp; excluding treated only: %s pp; "
                "against the baseline arm: %s pp"
                % (c["pure_villages"]["pp"], c["excl_treated"]["pp"],
                   c["vs_baseline_arm"]["pp"]))

    add("\n## Degrees oddity\n")
    e = json.load(open(os.path.join(C.OUT, "E_summary.json")))
    for c in e["checks"]:
        if c["item"].startswith("E1"):
            add("- declared anchor g0 = %.2f; model's own graduate share, years 22-29: "
                "%.4f-%.4f" % (c["g0"], c["mean_share_18_29"], c["max_share_18_29"]))
        if c["item"].startswith("E2"):
            add("- inside the arm: used = %.3f-%.3f, req = %.3f-%.3f (baseline 3.0), "
                "return = %.3f-%.3f (baseline 1.0)"
                % tuple(c["used_range"] + c["req_range"] + c["ret_range"]))
        if c["item"].startswith("E3"):
            add("- attainment change: upper secondary %+.4f, tertiary %+.4f, mean years %+.4f"
                % (c["completion_upper"]["diff"], c["completion_tertiary"]["diff"],
                   c["mean_years"]["diff"]))

    txt = "\n".join(L) + "\n"
    with open(os.path.join(C.OUT, "REPORT_NUMBERS.md"), "w") as fh:
        fh.write(txt)
    print(txt)
    return 0


if __name__ == "__main__":
    sys.exit(main())
